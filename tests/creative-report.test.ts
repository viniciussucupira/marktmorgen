import { creativeResultsReport } from "@/lib/channel-reports";
import { parseCsv } from "@/lib/csv";
import { done, is, part } from "./check";
const period = { from: "2026-10-07", to: "2026-10-13", currency: "usd" };
part("Variant export preserves full grouped records");
const rows = Array.from({length: 18}, (_,i) => ({source: i%2 ? "google" : "instagram", campaign: "launch", content: "variant-"+i, sales: i+1, cents: 12345+i}));
const csv = creativeResultsReport(rows,period);
const parsed = parseCsv(csv);
is("exports rows outside the displayed fifteen",parsed.rows.length,18);
is("exact period and grouped identity",parsed.rows[17].slice(0,7),[period.from,period.to,"USD","google","launch","variant-17","18"]);
is("minor units converted",parsed.rows[0][7],"123.45");
is("spreadsheet UTF8",csv.charCodeAt(0),0xfeff);
is("yen retained",parseCsv(creativeResultsReport(rows,{...period,currency:"jpy"})).rows[0][7],"12345");
is("three decimal currencies",parseCsv(creativeResultsReport(rows,{...period,currency:"kwd"})).rows[0][7],"12.345");
const hostile = {...rows[0],source:"=1+1",campaign:"+cmd",content:'name, "quoted"\nline'};
const escaped = parseCsv(creativeResultsReport([hostile],period)).rows[0];
is("source formula protected",escaped[3],"'=1+1");
is("campaign formula protected",escaped[4],"'+cmd");
is("variant punctuation roundtrips",escaped[5],hostile.content);
is("empty report has headers",parseCsv(creativeResultsReport([],period)).rows.length,0);
is("definitions included",parsed.rows[0][8].includes("not unique buyers"),true);
done();
