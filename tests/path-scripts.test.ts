import {pathScriptProducts,type PathScriptCatalog} from "@/lib/path-scripts";
import {KIND} from "@/lib/catalog";
import {done,is,part} from "./check";
const item=(id:string,kind:number=KIND.paid)=>({id,kind,options:[]});
const listing=(id:string,title="Guide",hidden=false)=>({id,title,hidden});
const catalog:PathScriptCatalog={items:[item("one"),item("two"),item("hidden",KIND.hidden),item("unsafe"),item("four")],head:[listing("foreign","Other store"),listing("one","First guide"),listing("one","Duplicate"),listing("hidden","Draft"),listing("unsafe","Passive income"),listing("two","Second guide"),listing("four","Fourth guide")],inline:null};
part("Only already-loaded published own products become script choices");
const before=JSON.stringify(catalog);
is("own indexed published safe names only",pathScriptProducts({catalog}),[{id:"one",title:"First guide"},{id:"two",title:"Second guide"},{id:"four",title:"Fourth guide"}]);
is("nothing is mutated",JSON.stringify(catalog),before);
is("no private record or prices in output",Object.keys(pathScriptProducts({catalog})[0]).sort(),["id","title"]);
is("no product read or invented default",pathScriptProducts({catalog:{...catalog,head:[],inline:null}}),[]);
const old:PathScriptCatalog={...catalog,head:[],inline:[listing("one","Legacy guide")]};
is("already-loaded legacy listing works",pathScriptProducts({catalog:old}),[{id:"one",title:"Legacy guide"}]);
is("listing's own draft flag is respected",pathScriptProducts({catalog:{...catalog,head:[listing("one","Guide",true)]}}),[]);
const limited:PathScriptCatalog={...catalog,items:Array.from({length:20},(_,i)=>item("p"+i)),head:Array.from({length:20},(_,i)=>listing("p"+i,"Guide "+i))};
is("only three choices",pathScriptProducts({catalog:limited}).length,3);
is("names beyond the cached-candidate bound are not read",pathScriptProducts({catalog:{...limited,head:limited.head.map((p,i)=>i<8?{...p,hidden:true}:p)}}),[]);
done();
