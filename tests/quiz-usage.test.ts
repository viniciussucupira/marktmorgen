import { readQuiz, parseQuiz, setupOf, parseSetup, submitQuiz, resetTries, dropQuiz, type Quiz } from "@/lib/quiz";
import type { Course } from "@/lib/course";
import { reserveQuizSubmission } from "@/lib/quiz-usage";
import { QUIZ_USAGE_POLICY, QUIZ_MONTHLY_SUBMISSIONS, quizUsageKey } from "@/lib/quiz-usage-rules";
import { store as redis } from "./redis-stub";
import { done, is, part } from "./check";
const sid = "c".repeat(32);
const raw = { passPercent: 100, attempts: 2, questions: [{ text: "Pick yes", choices: ["Yes", "No"], correct: [0] }] };
const made = readQuiz(raw);
if (!made.ok) throw Error("quiz");
const quiz = made.quiz;
const legacy: Quiz = { ...quiz, usagePolicy: undefined };
const course: Course = { id: "a".repeat(32), certificate: false, startsAt: null, modules: [{ id: "module000001", title: "Module", dripDays: 0, lessons: [{ id: "lesson000001", title: "Lesson", preview: false, video: null, files: [], link: null, hasBody: false, quiz: setupOf(quiz) }] }] };
const wrong = { [quiz.questions[0].id]: [1] };
async function main() {
  redis.clear();
  part("Stored policy, not caller preference");
  is("new quiz receives the current policy", quiz.usagePolicy, QUIZ_USAGE_POLICY);
  is("new client cannot remove the policy", readQuiz({ ...raw, usagePolicy: null }).ok && (readQuiz({ ...raw, usagePolicy: null }) as { quiz: Quiz }).quiz.usagePolicy, QUIZ_USAGE_POLICY);
  const edited = readQuiz({ ...raw, usagePolicy: undefined }, quiz);
  is("editing preserves the policy", edited.ok ? edited.quiz.usagePolicy : null, QUIZ_USAGE_POLICY);
  const old = readQuiz({ ...raw, usagePolicy: QUIZ_USAGE_POLICY }, legacy);
  is("editing does not cut legacy rights", old.ok ? old.quiz.usagePolicy : null, undefined);
  is("policy survives storage", parseQuiz(JSON.stringify(quiz))?.usagePolicy, QUIZ_USAGE_POLICY);
  is("policy survives course outline", parseSetup(setupOf(quiz))?.usagePolicy, QUIZ_USAGE_POLICY);
  is("unknown policy is not legacy", parseQuiz(JSON.stringify({ ...quiz, usagePolicy: "unknown" })), null);
  part("UTC month and isolation");
  const end = Date.UTC(2026, 11, 31, 23, 59, 59);
  is("December key", quizUsageKey(sid, end)?.endsWith("2026-12"), true);
  is("year boundary creates a new month", quizUsageKey(sid, end) !== quizUsageKey(sid, end + 1000), true);
  is("invalid store is refused", await reserveQuizSubmission(""), "unavailable");
  is("invalid clock is refused", quizUsageKey(sid, NaN), null);
  const key = quizUsageKey(sid)!;
  redis.run(["SET", key, QUIZ_MONTHLY_SUBMISSIONS - 1]);
  const concurrent = await Promise.all(Array.from({ length: 12 }, () => reserveQuizSubmission(sid)));
  is("only the last available slot is admitted concurrently", concurrent.filter(x => x === "ok").length, 1);
  is("other stores have their own allowance", await reserveQuizSubmission("d".repeat(32)), "ok");
  part("Reset and deletion cannot replenish allowance");
  redis.clear();
  redis.run(["SET", key, QUIZ_MONTHLY_SUBMISSIONS - 2]);
  is("first submission accepted", (await submitQuiz(course.id, "lesson000001", "learner", quiz, wrong, sid)).ok, true);
  await resetTries(course, "learner");
  const afterReset = await submitQuiz(course.id, "lesson000001", "learner", quiz, wrong, sid);
  is("reset restores learner tries", afterReset.ok ? afterReset.attempt.used : null, 1);
  await resetTries(course, "learner");
  await dropQuiz(course.id, "lesson000001");
  const exhausted = await submitQuiz(course.id, "another00001", "another", quiz, wrong, sid);
  is("another quiz and learner cannot bypass the shared limit", exhausted.ok ? "accepted" : exhausted.reason, "usage_limit");
  is("legacy is not retroactively blocked by the new budget", (await submitQuiz(course.id, "legacy000001", "legacy", legacy, wrong)).ok, true);
  is("new quiz without trusted store identity is refused", (await submitQuiz(course.id, "newquiz00001", "new", quiz, wrong)).ok, false);
  part("Uncertain reservations never grant work");
  const original = redis.pipeline;
  try {
    redis.pipeline = async () => [null, 1];
    is("missing counter is unavailable", await reserveQuizSubmission(sid), "unavailable");
    redis.pipeline = async () => [1, 0];
    is("unconfirmed retention is unavailable", await reserveQuizSubmission(sid), "unavailable");
    redis.pipeline = async () => { throw Error("network"); };
    is("network failure is unavailable", await reserveQuizSubmission(sid), "unavailable");
  } finally { redis.pipeline = original; }
  done();
}
main().catch(error => { console.error(error); process.exitCode = 1; });
