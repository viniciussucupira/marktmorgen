import {currentWordingSource} from "@/lib/path-wording-source";
import {pathIntroHash,type PathRecord} from "@/lib/path";
import type {Store} from "@/lib/store";
import {localDay} from "@/lib/path-rules";
import {done,is,part} from "./check";
const now=Date.now();
const store={sid:"a".repeat(32),name:"A public name",bio:"A public introduction",currency:"usd",catalog:{id:null,items:[],head:[],inline:null}} as unknown as Store;
const record:PathRecord={answers:{goalCents:700000,goalCurrency:"usd",skills:"Private skill words",subject:"Private topic words",minutes:15,audience:"instagram",timeZone:"America/New_York"},startedAt:now,checkins:[],best:-1,bestAt:0,money:null,counts:null};
part("The model source is derived again from own server records, without private free text");
const source=currentWordingSource(store,record,now)!;
is("next open mission is product",source.mission,"product");
is("personal topic is not forwarded",/Private|700000/.test(JSON.stringify(source)),false);
is("generic product instruction",source.step,"Make one product: a guide, a template, a checklist or a short course.");
const returning={...record,returnStep:{day:localDay(record.answers.timeZone,now),introHash:pathIntroHash(store.bio)}};
is("pending welcoming return takes priority",currentWordingSource(store,returning,now)?.mission,"return-intro");
is("the private return hash never leaves as wording",JSON.stringify(currentWordingSource(store,returning,now)).includes(returning.returnStep.introHash),false);
is("a server-read name change selects current facts",currentWordingSource({...store,name:"",bio:""},record,now)?.mission,"title");
is("reading an instruction records no completion",Object.keys(source).sort(),["mission","step"]);
is("record is not mutated",record.checkins,[]);
done();
