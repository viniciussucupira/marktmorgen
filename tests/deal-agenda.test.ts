import {createElement} from "react";
import {renderToStaticMarkup} from "react-dom/server";
import {DealAgenda} from "@/components/deal-agenda";
import {DEFAULT_STAGES,type Deal} from "@/lib/crm-rules";
import {is,done} from "./check";
const a:Deal={id:"aaaaaaaaaa",title:"<script>Later</script>",email:"a@example.com",cents:300,stage:"lead00",note:"<b>Note</b>",nextAction:"Call",dueDate:"2026-10-16",updatedAt:1,createdAt:1};
const b:Deal={...a,id:"bbbbbbbbbb",title:"Earlier",stage:"talk00",dueDate:"2026-10-15"};
const props={stages:DEFAULT_STAGES,currency:"usd",today:"2026-10-17",disabled:false,onEdit:()=>{}};
const html=renderToStaticMarkup(createElement(DealAgenda,{...props,deals:[b,a]}));
is("global row order retained",html.indexOf("Earlier")<html.indexOf("&lt;script&gt;Later"),true);
is("stage remains visible",html.includes("Talking")&&html.includes("New"),true);
is("UTC calendar dates retained",html.includes("2026-10-15")&&html.includes("Action date (UTC)"),true);
is("open dated action is overdue",html.includes("Overdue"),true);
is("closed opportunities not mislabeled overdue",renderToStaticMarkup(createElement(DealAgenda,{...props,deals:[{...a,stage:"won000"}]})).includes("Overdue"),false);
is("notes and titles escaped",html.includes("&lt;b&gt;Note&lt;/b&gt;")&&!html.includes("<script>"),true);
is("loaded contact and responsibility explicit",html.includes("a@example.com")&&html.includes("Unassigned"),true);
is("edit respects parent lock",renderToStaticMarkup(createElement(DealAgenda,{...props,deals:[a],disabled:true})).includes('disabled=""'),true);
is("no selection gives explicit message",renderToStaticMarkup(createElement(DealAgenda,{...props,deals:[]})).includes("No loaded deals match this selection"),true);
is("no invented date or amount for absent values",renderToStaticMarkup(createElement(DealAgenda,{...props,deals:[{...a,dueDate:"",cents:0}]})).includes("Not dated")&&renderToStaticMarkup(createElement(DealAgenda,{...props,deals:[{...a,cents:0}]})).includes("No amount yet"),true);
done();
