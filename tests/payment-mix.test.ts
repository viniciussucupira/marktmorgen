import { paymentMixFrom, paymentShare } from "@/lib/payment-mix";
import { PaymentMixPanel } from "@/components/payment-mix";
import { paymentMixReport } from "@/lib/channel-reports";
import { numbersContext, SECTIONS } from "@/lib/numbers-ask";
import { channelsTool } from "@/lib/mcp-tools";
import type { StatsData } from "@/lib/stats";
import { parseCsv } from "@/lib/csv";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const today=Date.UTC(2026,9,13);
const date=(ago:number)=>new Date(today-ago*86400000).toISOString().slice(0,10);
const days=Array.from({length:90},(_,i)=>({date:date(89-i),visitors:0,views:0,checkouts:0}));
const total={visitors:0,views:0,checkouts:0,sales:0,cents:0};
const data={sales:"ok",cashflowComplete:true,currency:"usd",days,totals:{d7:total,d30:total,d90:total,all:total},channels:{d7:[],d30:[],d90:[],all:[]},products:[],channelDays:{instagram:{[date(0)]:6000},google:{[date(1)]:2000},direct:{[date(0)]:500},"":{[date(0)]:500},unrecorded:{[date(0)]:500},imported:{[date(0)]:500},email:{[date(20)]:3000},tiktok:{[date(70)]:20000},outside:{[date(91)]:99999,[date(-1)]:99999}}} as unknown as StatsData;
part("Complete payment shares use all selected receipts");
const mix=paymentMixFrom(data,"d7")!;
is("selected UTC bounds",[mix.from,mix.to],[date(6),date(0)]);
is("full denominator",mix.total,10000);
is("shares conserve money",mix.rows.reduce((sum,r)=>sum+r.cents,0),mix.total);
is("largest identified channel",[mix.largest?.source,mix.largest?.share],["instagram",0.6]);
is("top three includes only identified channels",mix.topThreeShare,0.8);
is("unknown, pretracking and imported money",[mix.unidentified,mix.unidentifiedShare],[2000,0.2]);
is("blank source combines with direct",mix.rows.find(r=>r.source==="direct")?.cents,1000);
is("unidentified origins excluded from ranking",mix.rows.filter(r=>!r.identified).map(r=>r.source).sort(),["direct","imported","unrecorded"]);
is("thirty-day window",paymentMixFrom(data,"d30")?.total,13000);
is("ninety-day window",[paymentMixFrom(data,"d90")?.total,paymentMixFrom(data,"d90")?.largest?.source],[33000,"tiktok"]);
const directHeavy=paymentMixFrom({...data,channelDays:{direct:{[date(0)]:9000},instagram:{[date(0)]:1000}}},"d7")!;
is("largest unknown group isn't a marketing channel",[directHeavy.rows[0].source,directHeavy.largest?.source,directHeavy.largest?.share],["direct","instagram",0.1]);
const unknownOnly=paymentMixFrom({...data,channelDays:{direct:{[date(0)]:1000}}},"d7")!;
is("unidentified-only payments retain unknown origins",[unknownOnly.largest,unknownOnly.topThreeShare,unknownOnly.unidentifiedShare],[null,0,1]);
part("Missing coverage and invalid selected amounts stay unavailable");
is("partial read",paymentMixFrom({...data,partial:true},"d7"),null);
is("incomplete ledger",paymentMixFrom({...data,cashflowComplete:false},"d7"),null);
is("legacy missing ledger",paymentMixFrom({...data,channelDays:undefined},"d7"),null);
is("failed sales",paymentMixFrom({...data,sales:"error"},"d7"),null);
is("no date range",paymentMixFrom({...data,days:[]},"d7"),null);
for(const amount of [-1,NaN,Infinity,1.5]) is("invalid selected amount "+String(amount),paymentMixFrom({...data,channelDays:{instagram:{[date(0)]:amount}}},"d7"),null);
const empty=paymentMixFrom({...data,channelDays:{}},"d7")!;
is("zero payments don't invent shares",[empty.total,empty.largest,empty.unidentifiedShare,empty.topThreeShare],[0,null,null,null]);
is("unknown and rounded display",[paymentShare(null),paymentShare(0.12345)],["—","12.3%"]);
part("CSV and rendered panel preserve definitions");
const rows=parseCsv(paymentMixReport(mix,"usd")).rows;
is("csv amount, denominator and share",[rows[0][5],rows[0][6],rows[0][7],rows[0][9]],["60","60","100","80"]);
is("zero decimal currency",parseCsv(paymentMixReport(mix,"jpy")).rows[0][5],"6000");
is("three decimal currency",parseCsv(paymentMixReport(mix,"kwd")).rows[0][5],"6");
is("unknown rows labelled",rows.find(r=>r[3]==="direct")?.[4],"No");
is("formula source protected",parseCsv(paymentMixReport({...mix,rows:[{...mix.rows[0],source:"=1+1"}]},"usd")).rows[0][3],"'=1+1");
const render=(value:StatsData)=>renderToStaticMarkup(createElement(PaymentMixPanel,{data:value,range:"d7"}));
const html=render(data);
is("panel summary and download",[html.includes("Instagram · 60.0%"),html.includes("80.0%"),html.includes("Download payment shares")],[true,true,true]);
is("semantic labels and recorded scope",html.includes('scope="col"') && html.includes("including renewals") && html.includes("not profit"),true);
is("partial panel has no figures or download",[render({...data,partial:true}).includes("wait for complete figures"),render({...data,partial:true}).includes("Download payment shares")],[true,false]);
is("zero payment explanation",render({...data,channelDays:{}}).includes("Shares cannot be calculated"),true);
part("Assistant and read-only tools share exact aggregates");
const context=numbersContext(data).last_7_days as {payment_mix:{total_payments:string;largest_identified_channel:{share:string};unidentified_share:string}};
is("assistant summary",[context.payment_mix.total_payments,context.payment_mix.largest_identified_channel.share,context.payment_mix.unidentified_share],["$100","60.0%","20.0%"]);
is("assistant incomplete is null",(numbersContext({...data,partial:true}).last_7_days as {payment_mix:unknown}).payment_mix,null);
is("assistant can open panel",SECTIONS.includes("payment-mix"),true);
const tool=channelsTool(data,"d7");
is("tool keeps smallest units and fractional shares",[tool.payment_mix?.total_payments,tool.payment_mix?.top_three_identified_share],[10000,0.8]);
is("tool incomplete is null",channelsTool({...data,cashflowComplete:false},"d7").payment_mix,null);
is("no buyer identities exported",/receipt_email|customer_details|@example.com/.test(JSON.stringify(tool.payment_mix)),false);
done();
