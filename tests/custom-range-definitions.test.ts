import { customRangeComparison } from "@/lib/custom-range-comparison";
import { customRangeComparisonReport } from "@/lib/channel-reports";
import { CustomRangeComparison } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,channels:[],products:[],days:[],totals:{visitors:20,views:50,checkouts:5,sales:2,cents:1000},before:{visitors:40,views:60,checkouts:4,sales:1,cents:800}};
const model=customRangeComparison(data);
const parsed=parseCsv(customRangeComparisonReport(data));
const csvRows=parsed.rows.map(row=>Object.fromEntries(parsed.header.map((key,i)=>[key,row[i]])));
const html=renderToStaticMarkup(createElement(CustomRangeComparison,{range:data,currency:data.currency}));
part("Each metric carries its own explanation in the UI and CSV");
for(const metric of model.rows){
 const row=csvRows.find(row=>row.Metric===metric.name)!;
 is(metric.name+" has a nonempty definition",typeof metric.definition==="string"&&metric.definition.length>30,true);
 is(metric.name+" CSV uses the same definition",row.Definition.endsWith(metric.definition),true);
 is(metric.name+" appears in a definition term",html.includes(">"+metric.name+"</dt>"),true);
 is(metric.name+" has shared availability context",row.Definition.includes("Blank figures and changes mean unavailable or incomplete readings"),true);
}
is("definitions are distinct",new Set(model.rows.map(row=>row.definition)).size,10);
is("native disclosure can be opened with the keyboard",html.includes("<summary class=")&&html.includes("How metrics are calculated</summary>"),true);
is("explanations use a definition list",html.includes("<dl")&&html.includes("<dd>"),true);
is("disclosure is collapsed by default",html.includes("<details open"),false);
is("CSV count definition omits unrelated revenue-per-buyer formula",csvRows.find(row=>row.Metric==="Visitors")!.Definition.includes("Revenue per paid record is gross revenue divided"),false);
is("checkout definition retains independent coverage",csvRows.find(row=>row.Metric==="Checkouts per 100 visitors")!.Definition.includes("It is independent of paid coverage"),true);
is("paid ratio retains repeated-payment warning",csvRows.find(row=>row.Metric==="Paid records per 100 visitors")!.Definition.includes("can exceed 100 because of extras and repeated purchases"),true);
is("money scope remains available on every exported row",csvRows.every(row=>row.Definition.includes("exclude renewals")&&row.Definition.includes("not profit")),true);
is("visitor definition warns about estimates",model.rows.find(row=>row.name==="Visitors")!.definition.includes("not sums of daily counts or unique buyers"),true);
part("Changing explanations does not change figures or availability");
is("current values preserved",model.rows.map(row=>row.current),[20,50,5,2,1000,500,50,10,25,2.5]);
is("CSV schema preserved",parsed.header,["From (UTC)","To (UTC)","Previous from (UTC)","Previous to (UTC)","Currency","Metric","Unit","Current","Previous","Difference","Change (%)","Current available","Previous available","Paid coverage","Definition"]);
const partial=customRangeComparison({...data,partial:true});
is("partial paid values remain withheld",partial.rows.filter(row=>row.money||row.name.startsWith("Paid records")).every(row=>row.current===null),true);
is("partial traffic ratio remains available",partial.rows.find(row=>row.name==="Checkouts per 100 visitors")!.current,25);
is("definitions still exist for unavailable figures",partial.rows.every(row=>row.definition.length>30),true);
is("missing history remains missing",customRangeComparison({...data,before:null}).rows.every(row=>row.previous===null),true);
is("source values remain unchanged",data.totals.cents,1000);
done();
