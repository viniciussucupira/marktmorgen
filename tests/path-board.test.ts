import {claimHandle,ensureStatsId} from "@/lib/store";
import {startPath,readPath,visitPath,joinPathBoard,leavePathBoard,forgetPath} from "@/lib/path";
import {readPathBoardRows,PATH_BOARD_KEY,PATH_BOARD_OWNERS_KEY} from "@/lib/path-board";
import {PATH_BOARD_ROOM_BYTES,pathBoardRows,pathBoardScore} from "@/lib/path-board-rules";
import {readAnswers,NO_FACTS} from "@/lib/path-rules";
import {dataKey} from "@/lib/store-data";
import {redisPipeline} from "./redis-stub";
import {done,is,part} from "./check";
async function main(){
 const owner="board-private@example.com";await claimHandle(owner,"privateboard","Private Owner","One line");
 const store=(await ensureStatsId(owner))!;
 const now=Date.UTC(2026,9,19,12);
 const answer=readAnswers({goalCents:123456,skills:"private-skill",subject:"private-subject",minutes:15,audience:"none",timeZone:"UTC"},store.currency);
 if(!answer.ok)throw Error("answers");
 await startPath(store,answer.answers,now-86400000);
 is("membership starts off",(await readPath(store))!.board,undefined);
 is("stale facts cannot join",(await joinPathBoard(store,now)).ok,false);
 const initial=(await readPath(store))!;
 const counts={at:now,social:10,visitors:20,links:3,leads:1};
 const money={at:now,test:false,real:0,cents:0,currency:store.currency};
 await visitPath(store,{...initial,counts,money},now,async()=>false);
 part("Participation is one bounded pseudonymous entry");
 const joined=await joinPathBoard(store,now);if(!joined.ok)throw Error(joined.reason);
 const token=joined.record.board!.token;
 await joinPathBoard(store,now);
 const [members,slot]=await redisPipeline([["ZCARD",PATH_BOARD_KEY],["HGET",dataKey(store)!,"path-board"]]);
 is("idempotent join keeps one entry",members,1);
 is("shared bytes are reserved in the owner's room",Number(slot),PATH_BOARD_ROOM_BYTES);
 const rows=await readPathBoardRows(token);
 is("only one row",rows.length,1);
 is("pseudonym is generated",rows[0].alias,"Creator "+token.slice(0,12));
 is("no address or private answer",JSON.stringify(rows).includes(owner)||JSON.stringify(rows).includes("private-subject"),false);
 is("shared fields exclude money, level and store id",Object.keys(rows[0]).sort(),["alias","at","mine","rank","score","token"]);
 const stale=(await readPath(store))!;
 const oldScore=rows[0].score;
 await visitPath(store,{...stale,money:{...money,real:1,cents:100}},now,async()=>false);
 is("a server-confirmed sale updates the count",(await readPathBoardRows(token))[0].score,oldScore+1);
 const reached=(await readPath(store))!.best;
 await visitPath(store,{...(await readPath(store))!,money},now,async()=>false);
 is("a refund lowers the mission count",(await readPathBoardRows(token))[0].score,oldScore);
 is("the private reached level stays",(await readPath(store))!.best,reached);
 const beforeLeave=(await readPath(store))!;
 const left=await leavePathBoard(store,now);if(!left.ok)throw Error(left.reason);
 is("leaving preserves private answers",left.record.answers,beforeLeave.answers);
 is("leaving preserves days and level",[left.record.checkins,left.record.best],[beforeLeave.checkins,beforeLeave.best]);
 const [gone,lookup,room]=await redisPipeline([["ZCARD",PATH_BOARD_KEY],["HGET",PATH_BOARD_OWNERS_KEY,store.sid],["HGET",dataKey(store)!,"path-board"]]);
 is("shared entry and reverse lookup are removed",[gone,lookup,room],[0,null,null]);
 await visitPath(store,beforeLeave,now+86400000,async()=>false);
 is("a stale visit cannot restore consent",(await readPath(store))!.board,undefined);
 is("a stale visit cannot restore the shared entry",(await readPathBoardRows(token)).length,0);
 part("A new choice and erasure");
 const rejoined=await joinPathBoard(store,now);if(!rejoined.ok)throw Error(rejoined.reason);
 is("new choice gets a new pseudonym",rejoined.record.board!.token===token,false);
 await forgetPath(store);
 is("forgetting removes private Path",await readPath(store),null);
 is("forgetting removes board entry",(await readPathBoardRows(token)).length,0);
 const [reverse]=await redisPipeline([["HGET",PATH_BOARD_OWNERS_KEY,store.sid]]);
 is("forgetting removes reverse lookup",reverse,null);
 part("Ranking uses only mission counts and bounded valid output");
 const a="a".repeat(32),b="b".repeat(32);
 const ties=pathBoardRows([a+":4:"+now,"4",b+":4:"+now,"4"],a);
 is("equal counts share rank",ties.map(row=>row.rank),[1,1]);
 is("malformed, mismatched and invalid-date entries are omitted",pathBoardRows(["name:4:"+now,"4",a+":4:"+now,"5",a+":4:9007199254740991","4"],a),[]);
 is("money thresholds do not affect score",pathBoardScore({...NO_FACTS,revenueCents:100000000},answer.answers),pathBoardScore(NO_FACTS,answer.answers));
 done();
}
main().catch(error=>{console.error(error);process.exit(1);});
