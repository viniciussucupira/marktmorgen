import { customRangeComparison } from "@/lib/custom-range-comparison";
import { customRangeComparisonReport } from "@/lib/channel-reports";
import { CustomRangeComparison } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const name="Paid records per 100 visitors";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,channels:[],products:[],days:[{date:"2026-10-01",visitors:15,views:25,checkouts:10,sales:2,cents:500},{date:"2026-10-02",visitors:15,views:25,checkouts:10,sales:3,cents:500}],totals:{visitors:20,views:50,checkouts:20,sales:5,cents:1000},before:{visitors:40,views:60,checkouts:10,sales:4,cents:800}};
const metric=(d:RangeData)=>customRangeComparison(d).rows.find(row=>row.name===name)!;
const csv=(d:RangeData)=>{const parsed=parseCsv(customRangeComparisonReport(d));const row=parsed.rows.find(row=>row[5]===name)!;return Object.fromEntries(parsed.header.map((key,i)=>[key,row[i]]));};
const render=(d:RangeData)=>renderToStaticMarkup(createElement(CustomRangeComparison,{range:d,currency:d.currency}));
const html=(d:RangeData)=>{const all=render(d);const start=all.indexOf(">"+name+"</th>");return all.slice(start,all.indexOf("</tr>",start));};
part("Compare paid records against the period visitor estimate");
is("current ratio uses consolidated visitors",metric(data).current,25);
is("previous ratio uses its own denominator",metric(data).previous,10);
is("absolute difference uses records per 100 visitors",metric(data).difference,15);
is("relative growth compares ratios",metric(data).change,150);
is("unit is explicit and not monetary",[metric(data).unit,metric(data).money],["Records per 100 visitors",false]);
is("daily visitors are not summed",metric({...data,days:[]}).current,25);
is("revenue does not change the ratio",metric({...data,totals:{...data.totals,cents:999999}}).current,25);
is("checkouts do not become the numerator",metric({...data,totals:{...data.totals,checkouts:999}}).current,25);
is("CSV preserves ratio and absolute difference",[csv(data).Current,csv(data).Previous,csv(data).Difference],["25","10","15"]);
is("CSV relative change is percentage growth",csv(data)["Change (%)"],"150");
is("CSV unit is independent of currency",csv({...data,currency:"jpy"}).Current,"25");
is("KWD does not scale counts",csv({...data,currency:"kwd"}).Difference,"15");
is("UI shows signed ratio difference",html(data).includes("+15"),true);
is("UI shows relative percentage change",html(data).includes("+150%"),true);
is("UI does not format ratio as money",html(data).includes("$"),false);
part("Zero activity and missing history are distinct");
const zeroPaid={...data,totals:{...data.totals,sales:0}};
is("positive traffic and zero paid records is zero",metric(zeroPaid).current,0);
is("fall to zero has meaningful growth",metric(zeroPaid).change,-100);
const zeroPrior={...data,before:{...data.before!,sales:0}};
is("zero prior ratio preserves absolute difference",metric(zeroPrior).difference,25);
is("zero prior ratio has no relative growth",metric(zeroPrior).change,null);
const zeroVisitors={...data,totals:{...data.totals,visitors:0}};
is("no visitors does not invent zero conversion",metric(zeroVisitors).current,null);
is("no denominator withholds differences",[metric(zeroVisitors).difference,metric(zeroVisitors).change],[null,null]);
is("known previous survives no current visitors",metric(zeroVisitors).previous,10);
is("unavailable current exports blank",[csv(zeroVisitors).Current,csv(zeroVisitors)["Current available"]],["","No"]);
is("no prior visitors is unavailable",metric({...data,before:{...data.before!,visitors:0}}).previous,null);
is("absent prior history preserves current ratio",metric({...data,before:null}).current,25);
is("absent prior history has no comparison",[metric({...data,before:null}).previous,metric({...data,before:null}).difference],[null,null]);
is("unknown previous paid count is unavailable",metric({...data,before:{...data.before!,sales:null}}).previous,null);
for(const d of [{...data,partial:true},{...data,sales:"none" as const},{...data,sales:"error" as const}]){
 is("incomplete ledger withholds both ratios and changes",[metric(d).current,metric(d).previous,metric(d).difference,metric(d).change],[null,null,null,null]);
 is("incomplete ratios export blank",[csv(d).Current,csv(d).Previous,csv(d).Difference],["","",""]);
 is("incomplete ratio does not suppress traffic",customRangeComparison(d).rows.find(row=>row.name==="Visitors")?.current,20);
}
part("Honest definitions and analytical precision");
const repeated={...data,totals:{...data.totals,sales:30}};
is("repeated payments are not clamped to 100",metric(repeated).current,150);
is("fractional values are not rounded in the model",metric({...data,totals:{...data.totals,visitors:3,sales:1}}).current,1/3*100);
is("fractional values retain CSV precision",csv({...data,totals:{...data.totals,visitors:3,sales:1}}).Current,String(1/3*100));
for(const invalid of [-1,NaN,Infinity,1.5]) is("invalid paid count unavailable",metric({...data,totals:{...data.totals,sales:invalid}}).current,null);
for(const invalid of [-1,NaN,Infinity,1.5]) is("invalid visitor count unavailable",metric({...data,totals:{...data.totals,visitors:invalid}}).current,null);
is("definition disclaims buyer matching",csv(data).Definition.includes("not a matched-buyer conversion rate"),true);
is("definition explains extras and repeated purchases",csv(data).Definition.includes("can exceed 100 because of extras and repeated purchases"),true);
is("UI defines the ratio and difference",render(data).includes("Its difference is in records per 100 visitors"),true);
is("source totals remain unchanged",[data.totals.visitors,data.totals.sales,data.before!.sales],[20,5,4]);
done();
