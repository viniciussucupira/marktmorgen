import { campaignView,campaignSort,CAMPAIGN_SORTS } from "@/lib/campaign-view";
import type { CampaignResultRow, CampaignResults } from "@/lib/campaign-results";
import { campaignResultsReport } from "@/lib/channel-reports";
import { CampaignResultsPanel } from "@/components/campaign-results";
import { parseCsv } from "@/lib/csv";
import type { StatsData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done,is,part } from "./check";
const row=(campaign:string,gross:number|null,ads:number|null,channels:string[]|null):CampaignResultRow=>({campaign,paymentChannels:channels,adChannels:[],visits:10,paidRecords:gross===null ? null : 1,gross,ads,grossLessAds:gross===null || ads===null ? null : gross-ads});
const rows=[row("São-Paulo",1000,2000,["instagram","google"]),row("winter",3000,1000,["youtube"]),row("unknown",null,null,null),row("launch",2000,0,["email"])];
part("Search uses actual campaign and channel names");
is("accents and case ignored",campaignView(rows,"SAO", "name").map(r=>r.campaign),["São-Paulo"]);
is("multiple terms match across recorded fields",campaignView(rows,"  sao GOOGLE  ","name").map(r=>r.campaign),["São-Paulo"]);
is("friendly channel label searchable",campaignView([row("message",100,0,["device"])],"Shared from a phone","name").length,1);
is("ad-only channel searchable",campaignView([{...rows[1],adChannels:["tiktok"]}],"tiktok","ads").length,1);
is("missing channels not inferred",campaignView([rows[2]],"instagram","ads").length,0);
is("no matches is empty",campaignView(rows,"absent","ads"),[]);
part("Unknown values stay last and losses remain numeric");
is("spend ordering",campaignView(rows,"","ads").map(r=>r.campaign),["São-Paulo","winter","launch","unknown"]);
is("gross ordering",campaignView(rows,"","gross").map(r=>r.campaign),["winter","launch","São-Paulo","unknown"]);
is("losses first with unknown last",campaignView(rows,"","result-asc").map(r=>r.campaign),["São-Paulo","launch","winter","unknown"]);
is("highest result with deterministic tie",campaignView(rows,"","result-desc").map(r=>r.campaign),["launch","winter","São-Paulo","unknown"]);
const copy=JSON.stringify(rows);
campaignView(rows,"","gross");
is("original report not mutated",JSON.stringify(rows),copy);
is("unknown is never changed to zero",campaignView(rows,"unknown","gross")[0].gross,null);
is("invalid sort is constrained",campaignSort("bad"),"ads");
is("valid choices supported",CAMPAIGN_SORTS.map(s=>campaignSort(s.key)),CAMPAIGN_SORTS.map(s=>s.key));
part("Selection export retains scope and whole-report figures");
const report:CampaignResults={from:"2026-10-07",to:"2026-10-13",partial:false,salesKnown:true,unassignedAds:500,rows};
const filtered=campaignView(rows,"sao","ads");
const selected=parseCsv(campaignResultsReport({...report,rows:filtered},"usd",{query:"sao",sort:"Recorded ads: highest first",total:rows.length}));
is("only matched rows exported",selected.rows.length,1);
is("whole-report untagged spend preserved",selected.rows[0][11],"5");
is("filter and original scope recorded",selected.rows[0].slice(13),["sao","Recorded ads: highest first","4"]);
is("full report still exports all campaigns",parseCsv(campaignResultsReport(report,"usd")).rows.length,4);
is("formula query protected",parseCsv(campaignResultsReport({...report,rows:filtered},"usd",{query:"=1+1",sort:"ads",total:4})).rows[0][13],"'=1+1");
is("unknown figures stay blank in export",parseCsv(campaignResultsReport({...report,rows:[rows[2]]},"usd",{query:"unknown",sort:"gross",total:4})).rows[0].slice(7,11),["","","",""]);
part("Controls and downloads are accessible");
const data={currency:"usd",sales:"ok",days:[{date:report.from},{date:report.to}],posts:{d7:[{campaign:"launch",source:"instagram",sources:["instagram"],visits:10,sales:1,cents:1000}],d30:[],d90:[]}} as unknown as StatsData;
const html=renderToStaticMarkup(createElement(CampaignResultsPanel,{data,range:"d7",spends:[]}));
is("search and sort controls rendered",html.includes('type="search"') && html.includes("Sort campaigns") && html.includes("lowest first"),true);
is("displayed and full downloads distinguish scope",html.includes("Download displayed campaigns") && html.includes("Download campaign results") && html.includes("whole-report figure"),true);
is("visible campaign count",html.includes("Showing 1 of 1 campaigns"),true);
const multiple=renderToStaticMarkup(createElement("div",null,createElement(CampaignResultsPanel,{data,range:"d7",spends:[]}),createElement(CampaignResultsPanel,{data,range:"d7",spends:[]})));
const labels=[...multiple.matchAll(/for="([^"]+)"/g)].map(m=>m[1]);
is("control labels unique across panels",new Set(labels).size,4);
is("labels match fields",labels.every(id=>multiple.includes('id="'+id+'"')),true);
done();
