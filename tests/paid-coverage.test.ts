import { paidFiguresComplete } from "@/lib/paid-coverage";
import { numbersContext } from "@/lib/numbers-ask";
import { funnelTool,productsTool } from "@/lib/mcp-tools";
import { insightsFrom } from "@/lib/insights";
import type { StatsData } from "@/lib/stats";
import { claimHandle,ensureStatsId,storeForEmail } from "@/lib/store";
import { store as redis } from "./redis-stub";
import { done,is,part } from "./check";
const t={visitors:300,views:400,checkouts:50,sales:1,cents:424242};
const before={visitors:120,views:160,checkouts:20,sales:10,cents:110000};
const product=(id:string,title:string,views:number,cents:number,sales=1)=>({id,title,d7:{views,checkouts:views ? 20 : 0,sales,cents},d30:{views,checkouts:20,sales,cents},d90:{views,checkouts:20,sales,cents},all:{views,checkouts:20,sales,cents}});
const data={currency:"usd",sales:"ok",totals:{d7:t,d30:t,d90:t,all:t},previous:{d7:before,d30:before,d90:before},days:[{date:"2026-10-14",...t}],products:[product("paidonly01","Paid only",0,999999),product("traffic001","More views",100,100),product("traffic002","Less views",50,888888)],channels:{d7:[{source:"instagram",visits:300,checkouts:50,free:0,sales:3,cents:424242}],d30:[],d90:[]},posts:{d7:[],d30:[],d90:[]},ads:{d7:[],d30:[],d90:[]}} as unknown as StatsData;
const window=(value:StatsData)=>numbersContext(value).last_7_days as {sales?:number;revenue?:string;visitors:number;products:{product:string;sales?:number;revenue?:string}[];channels:{sales?:number;revenue?:string}[];the_same_number_of_days_before:{sales?:number;revenue?:string;visitors:number}};
async function main(){
  redis.clear();
  part("A successful response isn't always a complete paid read");
  is("coverage states",[paidFiguresComplete(data),paidFiguresComplete({...data,partial:true}),paidFiguresComplete({...data,sales:"error"}),paidFiguresComplete({...data,sales:"none"})],[true,false,false,false]);
  const partial={...data,partial:true};
  const context=numbersContext(partial);
  is("partial response distinguished from provider failure",context.sales_read,"incomplete purchase reading");
  is("explicit paid coverage",[context.paid_figures_complete,context.partial],[false,true]);
  const current=window(partial);
  is("current paid figures omitted",[current.sales,current.revenue],[undefined,undefined]);
  is("previous paid figures omitted",[current.the_same_number_of_days_before.sales,current.the_same_number_of_days_before.revenue],[undefined,undefined]);
  is("traffic retained in both periods",[current.visitors,current.the_same_number_of_days_before.visitors],[300,120]);
  is("channel paid figures omitted",[current.channels[0].sales,current.channels[0].revenue],[undefined,undefined]);
  is("product paid figures omitted",current.products.every(p=>p.sales===undefined && p.revenue===undefined),true);
  is("unavailable money can't drive product inclusion or rank",current.products.map(p=>p.product),["More views","Less views"]);
  is("complete product ranking can use paid amounts",window(data).products[0].product,"Paid only");
  is("complete figures retained",window(data).sales,1);
  part("Connected funnel retains traffic and withholds paid rates");
  const funnel=funnelTool(partial,"d7");
  is("paid rates are unknown",[funnel.sales,funnel.revenue,funnel.sales_per_checkout,funnel.sales_per_visitor],[null,null,null,null]);
  is("checkout per visitor still measured",funnel.checkouts_per_visitor,0.1667);
  is("prior paid values unknown",[funnel.the_same_days_before?.sales,funnel.the_same_days_before?.revenue],[null,null]);
  is("funnel coverage explicit",[funnel.paid_figures_complete,funnel.partial],[false,true]);
  is("complete funnel remains measured",[funnelTool(data,"d7").sales,funnelTool(data,"d7").revenue],[1,424242]);
  part("Connected products keep catalog and measured views");
  await claimHandle("coverage@example.com","coverage-store","Coverage Store","");
  await ensureStatsId("coverage@example.com");
  const store=(await storeForEmail("coverage@example.com"))!;
  const products=await productsTool(store,partial,"d7");
  is("product paid figures and rates unknown",products.products.every(p=>p.sales===null && p.revenue===null && p.sales_per_page_view===null),true);
  is("product traffic retained",products.products[0].page_views,100);
  is("product coverage explicit",[products.paid_figures_complete,products.partial],[false,true]);
  is("complete product values measured",(await productsTool(store,data,"d7")).products.find(p=>p.id==="paidonly01")?.revenue,999999);
  part("Paid-derived alerts wait for coverage while traffic remains useful");
  const completeInsights=insightsFrom(data,"d7",[],20);
  is("fixture exercises paid alerts",completeInsights.some(i=>i.text.includes("checkouts started") && /was paid|were paid/.test(i.text)),true);
  const partialInsights=insightsFrom(partial,"d7",[],20);
  is("no paid conversion, abandonment or revenue claim",partialInsights.some(i=>/bought:|was paid|were paid|of your money|no sale|not bought/.test(i.text)),false);
  is("traffic insight remains",partialInsights.some(i=>i.text.includes("More people visited")),true);
  is("no money arithmetic on partial reading",partialInsights.some(i=>i.math!==undefined),false);
  for(const state of ["error","none"] as const){
    const failed={...data,sales:state};
    is("failed context has no paid values "+state,window(failed).revenue,undefined);
    is("failed funnel has no paid rate "+state,funnelTool(failed,"d7").sales_per_checkout,null);
  }
  is("no buyer identities in context",JSON.stringify(context).includes("coverage@example.com"),false);
  done();
}
main().catch(error=>{console.error(error);process.exit(1);});
