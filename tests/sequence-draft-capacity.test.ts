import { appendSequenceDraft, keptSequenceSteps, sequenceDraftSlots } from "@/lib/sequence-draft";
import { done, is, part } from "./check";
part("AI sequence capacity without truncation");
const empty = { kind: "email", subject: "", body: "" };
const email = { kind: "email", subject: "Existing", body: "Content" };
const action = { kind: "note", subject: "", body: "" };
const generated = { ...email, subject: "Generated" };
is("blank placeholders do not use generated capacity", sequenceDraftSlots([empty, empty]), 10);
is("manual emails and actions use capacity", sequenceDraftSlots([email, action, empty]), 8);
is("partial subject remains protected", sequenceDraftSlots([{ ...empty, subject: "Work" }]), 9);
is("partial body remains protected", sequenceDraftSlots([{ ...empty, body: "Work" }]), 9);
is("whitespace placeholders can be replaced", sequenceDraftSlots([{ ...empty, subject: " ", body: "\n" }]), 10);
is("full sequence has no space", sequenceDraftSlots(Array(10).fill(email)), 0);
is("overfull sequence never has negative space", sequenceDraftSlots(Array(11).fill(email)), 0);
is("keeps existing order and action", keptSequenceSteps([email, empty, action]), [email, action]);
is("appends generated steps after all protected steps", appendSequenceDraft([email, empty, action], [generated]), [email, action, generated]);
is("exact fit retains all ten", appendSequenceDraft(Array(7).fill(email), Array(3).fill(generated)).length, 10);
is("overflow is visible rather than silently truncated", appendSequenceDraft(Array(9).fill(email), Array(3).fill(generated)).length, 12);
const source = [email, empty, action];
appendSequenceDraft(source, [generated]);
is("source steps are unchanged", source, [email, empty, action]);
done();
