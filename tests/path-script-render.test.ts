import {createElement} from "react";
import {renderToStaticMarkup} from "react-dom/server";
import {PathSocialScripts} from "@/components/path-social-scripts";
import {PathMissions} from "@/components/path-missions";
import {PathGrowthMissions} from "@/components/path-growth-missions";
import {pathGrowthMissions} from "@/lib/path-growth-rules";
import {NO_FACTS,dayMissions,trafficMissions} from "@/lib/path-rules";
import {SCRIPT_WORDS} from "@/lib/path-script-rules";
import {done,is,part} from "./check";
const products=[{id:"one",title:"Workshop workbook"},{id:"two",title:"A second guide"}];
const html=renderToStaticMarkup(createElement(PathSocialScripts,{products,answers:{minutes:15,audience:"youtube"},productsHref:"/studio?store=0123456789abcdef0123456789abcdef#products"}));
part("The actual script controls render with labels, privacy and a bounded response");
is("named script field is present",html.includes("Script to adapt"),true);
is("native read-only text field",/<textarea[^>]*readonly/i.test(html),true);
is("chosen audience starts on YouTube",html.includes("Video title: A closer look at Workshop workbook"),true);
is("product picker is labeled",html.includes('for="path-script-product"'),true);
is("platform picker is labeled",html.includes('for="path-script-platform"'),true);
is("copy is an explicit button",html.includes(SCRIPT_WORDS.copy),true);
is("copy help says nothing is posted",html.includes("does not publish a post"),true);
is("no completion or automatic post form",html.includes("<form"),false);
is("native status announces copy outcome",html.includes('role="status"'),true);
const largest=renderToStaticMarkup(createElement(PathSocialScripts,{products:Array.from({length:3},(_,i)=>({id:"p"+i,title:"&".repeat(160)})),answers:{minutes:60,audience:"instagram"},productsHref:"/studio#products"}));
is("extra response stays in existing Path envelope",Buffer.byteLength(largest,"utf8")<12_000,true);
const privateAnswers={minutes:30 as const,audience:"tiktok" as const,goalCents:999999,skills:"secret craft",subject:"private subject"};
const privateHtml=renderToStaticMarkup(createElement(PathSocialScripts,{products,answers:privateAnswers,productsHref:"/studio#products"}));
is("no goal or free text enters scripts",/999999|secret craft|private subject/.test(privateHtml),false);
const empty=renderToStaticMarkup(createElement(PathSocialScripts,{products:[],answers:{minutes:15,audience:"none"},productsHref:"/studio#products"}));
is("empty list explains the next step",empty.includes(SCRIPT_WORDS.empty),true);
is("empty list invents no draft",empty.includes("<textarea"),false);
const guidance=renderToStaticMarkup(createElement(PathMissions,{missions:[...dayMissions(NO_FACTS,{minutes:60,audience:"instagram",subject:"&".repeat(80),skills:"&".repeat(120)}),...trafficMissions(NO_FACTS)],hrefFor:()=>"/studio#products"}));
const growth=renderToStaticMarkup(createElement(PathGrowthMissions,{missions:pathGrowthMissions({realSale:true,fileProducts:null,listEmailSent:null,repeatBuyer:null,postPurchaseOffer:null,buyerReview:null,keptOrders:null}),hrefFor:()=>"/studio#products",read:false,moneyAt:null}));
is("all guidance leaves room within the unchanged 70 KB page envelope",Buffer.byteLength(guidance+growth+largest,"utf8")<52_000,true);
done();
