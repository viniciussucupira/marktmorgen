import {createElement} from "react";
import {renderToStaticMarkup} from "react-dom/server";
import {PathGrowthMissions} from "@/components/path-growth-missions";
import {PathMissions} from "@/components/path-missions";
import {pathGrowthMissions} from "@/lib/path-growth-rules";
import {NO_FACTS,dayMissions,trafficMissions} from "@/lib/path-rules";
import {done,is,part} from "./check";
const hrefFor=()=>"/studio/email?store=0123456789abcdef0123456789abcdef";
const missions=pathGrowthMissions({realSale:true,fileProducts:null,listEmailSent:null,repeatBuyer:null,postPurchaseOffer:null,buyerReview:null,keptOrders:null});
const html=renderToStaticMarkup(createElement(PathGrowthMissions,{missions,hrefFor,read:false,moneyAt:null}));
part("Post-sale instructions remain private guidance with a bounded response");
is("six native disclosures",(html.match(/<details/g)||[]).length,6);
is("no manual completion controls",/<input|<button|<form/.test(html),false);
is("no added client script",html.includes("<script"),false);
is("all destinations scoped to this store",(html.match(/href="/g)||[]).length,6);
is("missing evidence is visible",html.includes("Not verified in this reading."),true);
is("bounded additional response",Buffer.byteLength(html,"utf8")<12_000,true);
is("no section before first sale",renderToStaticMarkup(createElement(PathGrowthMissions,{missions:[],hrefFor,read:false,moneyAt:null})),"");
const answers={minutes:60 as const,audience:"instagram" as const,subject:"&".repeat(80),skills:"&".repeat(120)};
const original=renderToStaticMarkup(createElement(PathMissions,{missions:[...dayMissions(NO_FACTS,answers),...trafficMissions(NO_FACTS)],hrefFor}));
is("combined mission guidance leaves room inside the existing 70 KB page response",Buffer.byteLength(original+html,"utf8")<40_000,true);
done();
