import { attributionTable } from "@/lib/attribution-rules";
import { attributionReport } from "@/lib/channel-reports";
import { AttributionTable } from "@/components/attribution-table";
import { parseCsv } from "@/lib/csv";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const period = {from:"2026-10-07",to:"2026-10-13",currency:"usd"};
part("Unattributed columns remain independent");
const table = attributionTable([{source:"instagram",sales:2,cents:5000},{source:"direct",sales:1,cents:12345}],[{source:"youtube",sales:1,cents:1000},{source:"",sales:2,cents:16345}],[{answer:"podcast",buyers:1,cents:12345,unknownBuyers:1,unknownCents:12345}]);
is("last no channel",table.unknown,{sales:1,cents:12345});
is("first no channel includes empty sources",table.unknownFirst,{sales:2,cents:16345});
is("first and last conserve gross",[table.rows.reduce((n,r)=>n+r.last.cents,table.unknown.cents),table.rows.reduce((n,r)=>n+r.first.cents,table.unknownFirst?.cents ?? 0)],[17345,17345]);
const onlyFirst = attributionTable([{source:"instagram",sales:1,cents:1000}],[{source:"direct",sales:1,cents:1000}],[]);
is("first-only unknown isn't borrowed from last",[onlyFirst.unknown.cents,onlyFirst.unknownFirst?.cents],[0,1000]);
part("Export explains alternative models and subsets");
const text = attributionReport(table,period);
const rows = parseCsv(text).rows;
const unknown = rows.find(r=>r[3]==="No channel")!;
is("period and currency travel with figures",unknown.slice(0,3),[period.from,period.to,"USD"]);
is("both unattributed figures exported",unknown.slice(5,11),["1","123.45","2","163.45","",""]);
const subset = rows.find(r=>r[3].startsWith("Answer subset"))!;
is("answer subsets have no visit revenue",subset.slice(5,11),["","","","","1","123.45"]);
is("subset definition prevents double count",subset[11].includes("overlap channel rows"),true);
is("zero decimal currency",parseCsv(attributionReport(table,{...period,currency:"jpy"})).rows.find(r=>r[3]==="No channel")?.[6],"12345");
is("three decimal currency",parseCsv(attributionReport(table,{...period,currency:"kwd"})).rows.find(r=>r[3]==="No channel")?.[6],"12.345");
const legacy = {...table,unknownFirst:undefined};
is("legacy unknown first stays blank",parseCsv(attributionReport(legacy,period)).rows.find(r=>r[3]==="No channel")?.slice(7,9),["",""]);
is("legacy channel first figures also blank",parseCsv(attributionReport(legacy,period)).rows.filter(r=>r[3]==="Channel").every(r=>r[7]==="" && r[8]===""),true);
is("missing first reading preserves unavailable",attributionTable([{source:"instagram",sales:1,cents:1000}],undefined,[]).unknownFirst,undefined);
const hostile = {...table,rows:[{...table.rows[0],name:"=1+1"}]};
is("spreadsheet formula protected",parseCsv(attributionReport(hostile,period)).rows[0][4],"'=1+1");
is("no buyer identities exported",/@|receipt_email|customer_details/.test(text),false);
part("Panel displays both no-channel readings and download");
const render = (value: typeof table) => renderToStaticMarkup(createElement(AttributionTable,{table:value,days:30,canSet:false,span:"7 days",money:n=>"$"+(n/100).toFixed(2),count:String,period}));
const html=render(onlyFirst);
is("first-only no-channel row visible",html.includes("No channel") && html.includes("$10.00"),true);
is("download offered",html.includes("Download attribution comparison"),true);
is("models must not be added",html.includes("must not be added together"),true);
is("legacy values explicitly unavailable",render(legacy).includes("Unavailable"),true);
done();
