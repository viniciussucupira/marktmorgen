import { customRangeComparison } from "@/lib/custom-range-comparison";
import { customRangeComparisonReport } from "@/lib/channel-reports";
import { CustomRangeComparison } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import type { RangeData } from "@/lib/stats";
import { done, is, part } from "./check";
const name="Revenue per paid record";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,channels:[],products:[],days:[{date:"2026-10-01",visitors:10,views:10,checkouts:1,sales:1,cents:10000},{date:"2026-10-02",visitors:20,views:20,checkouts:2,sales:2,cents:200}],totals:{visitors:30,views:30,checkouts:3,sales:3,cents:10200},before:{visitors:10,views:10,checkouts:2,sales:2,cents:2000}};
const metric=(d:RangeData)=>customRangeComparison(d).rows.find(row=>row.name===name)!;
const report=(d:RangeData)=>{const parsed=parseCsv(customRangeComparisonReport(d));const row=parsed.rows.find(row=>row[5]===name)!;return Object.fromEntries(parsed.header.map((key,i)=>[key,row[i]]));};
const html=(d:RangeData)=>{const all=renderToStaticMarkup(createElement(CustomRangeComparison,{range:d,currency:d.currency}));const start=all.indexOf(">"+name+"</th>");return all.slice(start,all.indexOf("</tr>",start));};
part("Period-weighted gross revenue per paid record");
is("current uses whole-period totals, not mean of daily averages",metric(data).current,3400);
is("previous has its own denominator",metric(data).previous,1000);
is("absolute difference uses unrounded averages",metric(data).difference,2400);
is("relative change compares average values",metric(data).change,240);
is("average is explicitly monetary",metric(data).money,true);
is("model keeps currency",metric(data).unit,"USD");
is("display current money",html(data).includes("$34"),true);
is("display previous money",html(data).includes("$10"),true);
is("display signed monetary difference",html(data).includes("+$24"),true);
is("display relative change",html(data).includes("+240%"),true);
is("CSV converts to major units",[report(data).Current,report(data).Previous,report(data).Difference],["34","10","24"]);
is("CSV keeps the same relative change",report(data)["Change (%)"],"240");
part("No payments, unavailable history and incomplete purchases");
const noPayments={...data,totals:{...data.totals,sales:0,cents:0}};
is("no current payments has no defined average",metric(noPayments).current,null);
is("no current payments has no change",metric(noPayments).difference,null);
is("confirmed prior average survives current zero payments",metric(noPayments).previous,1000);
is("missing history keeps current average",metric({...data,before:null}).current,3400);
is("missing history has no previous average",metric({...data,before:null}).previous,null);
for(const before of [{...data.before!,sales:0,cents:0},{...data.before!,sales:null},{...data.before!,cents:null}]){
 is("unknown or empty prior denominator has no previous average",metric({...data,before}).previous,null);
 is("unknown or empty prior has no change",metric({...data,before}).change,null);
}
for(const d of [{...data,partial:true},{...data,sales:"none" as const},{...data,sales:"error" as const}]){
 const row=metric(d);
 is("incomplete coverage withholds all average values",[row.current,row.previous,row.difference,row.change],[null,null,null,null]);
 is("unavailable average remains blank in CSV",[report(d).Current,report(d).Previous,report(d).Difference],["","",""]);
 is("unavailable average shows no money in UI",html(d).includes("Unavailable")&&!html(d).includes("$"),true);
}
const zeroRevenue={...data,totals:{...data.totals,cents:0},before:{...data.before!,cents:0}};
is("confirmed zero revenue with paid records stays zero",metric(zeroRevenue).current,0);
is("zero average retains zero absolute difference",metric(zeroRevenue).difference,0);
is("zero prior average has no relative percentage",metric(zeroRevenue).change,null);
part("Analytical precision, currency scaling and malformed denominators");
const fractional={...data,totals:{...data.totals,cents:100,sales:3}};
is("average does not round minor units",metric(fractional).current,100/3);
is("CSV preserves analytical precision",report(fractional).Current,String((100/3)/100));
is("USD display rounds only for presentation",html(fractional).includes("$0.33"),true);
is("JPY CSV has no cent conversion",report({...fractional,currency:"jpy"}).Current,String(100/3));
is("three-decimal currency uses its own scale",report({...fractional,currency:"kwd"}).Current,String((100/3)/1000));
for(const sales of [NaN,Infinity,-1,0.5])is("invalid count cannot create an average",metric({...data,totals:{...data.totals,sales}}).current,null);
is("non-finite amount cannot create an average",metric({...data,totals:{...data.totals,cents:Infinity}}).current,null);
is("scope explains the denominator",report(data).Definition.includes("not revenue per buyer"),true);
is("empty denominator is explained",report(data).Definition.includes("No paid records means the average is unavailable"),true);
is("source figures are unchanged",[data.totals.cents,data.totals.sales],[10200,3]);
done();
