import { customRangeComparison } from "@/lib/custom-range-comparison";
import { customRangeComparisonReport } from "@/lib/channel-reports";
import { CustomRangeComparison, CustomRangeResults } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import { toMajor } from "@/lib/money";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const data:RangeData={from:"2026-03-01",to:"2026-03-03",currency:"usd",sales:"ok",partial:false,elsewhere:0,days:[],channels:[],products:[],totals:{visitors:20,views:60,checkouts:0,sales:3,cents:10103},before:{visitors:10,views:80,checkouts:0,sales:1,cents:9902}};
const find=(d:RangeData,name:string)=>customRangeComparison(d).rows.find(row=>row.name===name)!;
const render=(d=data)=>renderToStaticMarkup(createElement(CustomRangeComparison,{range:d,currency:d.currency}));
const htmlRow=(html:string,name:string)=>{const at=html.indexOf(">"+name+"</th>");return html.slice(at,html.indexOf("</tr>",at));};
part("Equal consecutive periods and exact absolute changes");
is("previous dates cross month",customRangeComparison(data).previousFrom,"2026-02-26");
is("previous dates end just before selected days",customRangeComparison(data).previousTo,"2026-02-28");
is("leap dates preserved",customRangeComparison({...data,from:"2024-03-01",to:"2024-03-03"}).previousFrom,"2024-02-27");
is("single-day comparison",customRangeComparison({...data,from:"2026-01-01",to:"2026-01-01"}).previousTo,"2025-12-31");
is("positive traffic difference",find(data,"Visitors").difference,10);
is("positive traffic percent",find(data,"Visitors").change,100);
is("negative traffic difference",find(data,"Page views").difference,-20);
is("negative traffic percent",find(data,"Page views").change,-25);
is("smallest currency units preserved",find(data,"Gross revenue").difference,201);
is("zero absolute difference stays zero",find(data,"Checkouts").difference,0);
is("zero previous has no percentage",find(data,"Checkouts").change,null);
is("positive current with zero previous has no percentage",find({...data,before:{...data.before!,visitors:0}},"Visitors").change,null);
part("Unknown readings never become zero");
const missing={...data,before:null};
is("missing previous values stay null",customRangeComparison(missing).rows.every(row=>row.previous===null),true);
is("missing previous changes stay null",customRangeComparison(missing).rows.every(row=>row.difference===null&&row.change===null),true);
const unknownPaid={...data,before:{...data.before!,sales:null,cents:null}};
is("unknown previous money stays null",find(unknownPaid,"Gross revenue").previous,null);
is("confirmed current money survives",find(unknownPaid,"Gross revenue").current,10103);
for(const d of [{...data,partial:true},{...data,sales:"none" as const},{...data,sales:"error" as const}]){
 is(d.sales+"/"+d.partial+" paid values withheld",customRangeComparison(d).rows.slice(3).every(row=>row.current===null&&row.previous===null&&row.difference===null&&row.change===null),true);
 is(d.sales+"/"+d.partial+" traffic remains",find(d,"Visitors").difference,10);
}
part("Rendered comparison explains values and supports keyboard access");
const html=render();
is("native comparison disclosure",html.includes("<details")&&html.includes("Compare with previous period"),true);
is("scroll region reachable",html.includes('tabindex="0" role="region" aria-label="Period comparison"'),true);
is("semantic row and column headers",html.includes('scope="row"')&&html.includes('scope="col"'),true);
is("exact selected dates visible",html.includes("Mar 1, 2026 to Mar 3, 2026"),true);
is("exact previous dates visible",html.includes("Feb 26, 2026 to Feb 28, 2026"),true);
is("current and previous money visible",htmlRow(html,"Gross revenue").includes("$101.03")&&htmlRow(html,"Gross revenue").includes("$99.02"),true);
is("signed cent difference visible",htmlRow(html,"Gross revenue").includes("+$2.01"),true);
is("negative count difference visible",htmlRow(html,"Page views").includes("-20"),true);
is("zero prior explained",html.includes("previous value is zero"),true);
is("unknown money renders unavailable",htmlRow(render({...data,partial:true}),"Gross revenue").includes("Unavailable"),true);
is("unknown money does not leak",htmlRow(render({...data,partial:true}),"Gross revenue").includes("$"),false);
is("missing previous renders unavailable",htmlRow(render(missing),"Visitors").includes("Unavailable"),true);
is("paid counting scope explained",html.includes("include one-click extras and exclude renewals"),true);
is("comparison included in actual results",renderToStaticMarkup(createElement(CustomRangeResults,{range:{...data,products:[]},marks:[],currency:"usd"})).includes("Compare with previous period"),true);
part("CSV and displayed model share exact amounts and availability");
for(const d of [data,missing,unknownPaid,{...data,partial:true}]){
 const model=customRangeComparison(d);const parsed=parseCsv(customRangeComparisonReport(d));
 const rows=parsed.rows.map(row=>Object.fromEntries(parsed.header.map((key,i)=>[key,row[i]])));
 is("CSV current values match model",rows.map(row=>row.Current),model.rows.map(row=>row.current===null?"":String(row.name==="Gross revenue"?toMajor(row.current,d.currency):row.current)));
 is("CSV differences match model",rows.map(row=>row.Difference),model.rows.map(row=>row.difference===null?"":String(row.name==="Gross revenue"?toMajor(row.difference,d.currency):row.difference)));
}
is("input is unchanged",data.before!.cents,9902);
done();
