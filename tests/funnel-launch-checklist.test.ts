import { funnelLaunchChecklist } from "@/lib/funnel-launch-checklist";
import { funnelLaunchIssues } from "@/lib/funnel-launch-review";
import { done,is,part } from "./check";
const step={title:"Checkout\n[done]",open:true,why:"",product:true,free:false,seen:987654,done:54321,buyer:"secret@example.com",amount:1234567};
part("A saved review is a manual handoff, never a conversion certification");
const issues=funnelLaunchIssues(false,[step],null);
const checklist=funnelLaunchChecklist("My funnel\nsecond line",false,[step],issues);
is("disabled and unchecked payments stay explicit",checklist.includes("The funnel address is disabled")&&checklist.includes("Store payments have not been checked"),true);
is("manual checkboxes do not mark a test done",checklist.includes("[x]"),false);
is("names cannot inject new checklist lines",checklist.includes("Funnel: My funnel second line")&&checklist.includes("Step 1: Checkout [done]"),true);
is("buyer records and measured totals stay private",[step.buyer,String(step.seen),String(step.done),String(step.amount)].some(secret=>checklist.includes(secret)),false);
is("paid checkout asks for sandbox verification",checklist.includes("payment provider's sandbox"),true);
const free={title:"Guide",open:false,why:"",product:true,free:true};
const freeList=funnelLaunchChecklist("Free journey",true,[free],funnelLaunchIssues(true,[free],true));
is("unavailable step is not called ready",freeList.includes("unavailable in saved review"),true);
is("free journey has no payment-test instruction",freeList.includes("payment provider's sandbox"),false);
const clear=funnelLaunchChecklist("Clear",true,[{...free,open:true}],[]);
is("clear saved review still requires manual checks",clear.includes("Manual testing is still required.")&&clear.includes("not proof of a working checkout"),true);
is("empty saved journey requires a step",funnelLaunchChecklist("Empty",false,[],[]).includes("Add and review at least one step."),true);
done();
