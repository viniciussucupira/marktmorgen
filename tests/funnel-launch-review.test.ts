import { funnelLaunchIssues } from "@/lib/funnel-launch-review";
import { is, done } from "./check";
const page = { title: "Welcome", open: true, why: "", product: false, free: false };
const paid = { title: "Course", open: true, why: "", product: true, free: false };
const free = { ...paid, title: "Guide", free: true };
is("live page-only journey has no payment requirement", funnelLaunchIssues(true, [page], false), []);
is("free sign-up is not treated as a paid checkout", funnelLaunchIssues(true, [free], false), []);
is("disabled funnel has a settings issue", funnelLaunchIssues(false, [page], true).map(issue => issue.code), ["disabled"]);
is("empty funnel requests a step", funnelLaunchIssues(true, [], true).map(issue => issue.code), ["empty"]);
is("disabled empty funnel retains both independent issues", funnelLaunchIssues(false, [], false).map(issue => issue.code), ["disabled", "empty"]);
is("visible paid offer requires available store payments", funnelLaunchIssues(true, [paid], false).map(issue => issue.code), ["payments"]);
is("unknown payment status cannot pass", funnelLaunchIssues(true, [paid], null).map(issue => issue.code), ["payments_unknown"]);
is("available store payments clear only that configuration issue", funnelLaunchIssues(true, [paid], true), []);
is("hidden paid step does not produce a misleading payment blocker", funnelLaunchIssues(true, [{ ...paid, open: false, why: "Draft" }], false).map(issue => issue.code), ["step"]);
const blocked = funnelLaunchIssues(true, [page, { ...paid, open: false, why: "Product is a draft." }], true);
is("blocked step retains its original position", blocked[0].stepIndex, 1);
is("blocked step explains saved reason", blocked[0].detail, "Product is a draft.");
is("missing reason has a useful fallback", funnelLaunchIssues(true, [{ ...page, open: false }], true)[0].detail.includes("unavailable"), true);
is("multiple paid steps share one store payment issue", funnelLaunchIssues(true, [paid, paid], false).length, 1);
const input = [{ ...page, open: false }];
const original = JSON.stringify(input);
funnelLaunchIssues(false, input, null);
is("review never edits visibility or configuration", JSON.stringify(input), original);
done();
