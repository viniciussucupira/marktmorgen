import { CustomRangeSelectionSummary } from "@/components/custom-range";
import { customRangeSelectionReport } from "@/lib/channel-reports";
import { customRangeView } from "@/lib/custom-range-view";
import { revenuePerTraffic } from "@/lib/custom-range-efficiency";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,before:null,days:[],totals:{visitors:999,views:999,sales:999,checkouts:999,cents:999999},channels:[{source:"google",visits:1,sales:1,cents:1000},{source:"email",visits:99,sales:1,cents:1000}],products:[{id:"google",views:2,checkouts:1,sales:1,cents:1000},{id:"email",views:98,checkouts:2,sales:2,cents:3000}],channelsTotal:50,channelsTruncated:true,productsTotal:60,productsTruncated:true};
const records=(d:RangeData)=>{const p=parseCsv(customRangeSelectionReport(d));return p.rows.map(row=>Object.fromEntries(p.header.map((key,i)=>[key,row[i]])));};
const render=(range:RangeData)=>renderToStaticMarkup(createElement(CustomRangeSelectionSummary,{range,currency:range.currency}));
const values=(d:RangeData)=>records(d).map(r=>r["Revenue per traffic event"]);
part("Selection ratio is weighted by recorded traffic");
is("independent list ratios",values(data),["0.2","0.4"]);
is("UI channel total ratio",render(data).includes(">$0.2</td>"),true);
is("UI product total ratio",render(data).includes(">$0.4</td>"),true);
is("not the average of channel ratios",Number(values(data)[0])===(1000/1+1000/99)/2/100,false);
is("period totals do not replace loaded sums",values({...data,totals:{...data.totals,cents:1,visitors:1}}),values(data));
is("source limits remain visible",records(data).map(r=>r["Source list truncated"]),["Yes","Yes"]);
is("definition explains weighted calculation",records(data).every(r=>r.Definition.includes("not the average of row ratios")),true);
is("UI explains weighted calculation",render(data).includes("not the average of row ratios"),true);
is("overlapping lists remain separate",records(data).map(r=>r.List),["Channels","Products"]);
is("traffic units explicit",records(data).map(r=>r["Traffic unit"]),["Visits","Page views"]);
part("The ratio follows loaded selection and preserves availability");
const selected=customRangeView(data,"email");
is("selected channel ratio",values(selected)[0],String((1000/99)/100));
is("selected product ratio",values(selected)[1],String((3000/98)/100));
is("traffic threshold changes weighted total",values(customRangeView(data,"","recorded","all",10)),values(selected));
is("sorting does not change the ratio",values(customRangeView(data,"","efficiency_desc")),values(data));
const empty={...data,channels:[],products:[]};
is("empty selection is unavailable ratio",values(empty),["",""]);
is("empty UI shows unavailable ratio",render(empty).includes(">Unavailable</td>"),true);
const noTraffic={...data,channels:data.channels.map(r=>({...r,visits:0})),products:data.products.map(r=>({...r,views:0}))};
is("zero traffic with money is unavailable",values(noTraffic),["",""]);
const free={...data,channels:data.channels.map(r=>({...r,cents:0})),products:data.products.map(r=>({...r,cents:0}))};
is("confirmed zero revenue remains zero",values(free),["0","0"]);
is("zero ratio visible in UI",render(free).includes(">$0</td>"),true);
for(const d of [{...data,partial:true},{...data,sales:"none" as const},{...data,sales:"error" as const}]){
 is("unknown paid ratio blank",values(d),["",""]);
 is("unknown paid ratio unavailable in UI",(render(d).match(/>Unavailable<\/td>/g)??[]).length,6);
 is("traffic preserved independently",records(d).map(r=>r.Traffic),["100","100"]);
}
is("null total cannot become zero",revenuePerTraffic(null,100,true),null);
part("Currency and calculated precision remain correct");
is("JPY keeps minor-unit scale",values({...data,currency:"jpy"}),["20","40"]);
is("KWD uses three-decimal scale",values({...data,currency:"kwd"}),["0.02","0.04"]);
const fractional={...data,channels:[{source:"email",visits:3,sales:1,cents:100}]};
is("CSV keeps fractional precision",values(fractional)[0],String((100/3)/100));
is("UI rounds analytically",render(fractional).includes(">$0.3333</td>"),true);
const tiny={...data,channels:[{source:"email",visits:100000,sales:1,cents:1}]};
is("tiny selection ratio stays visible",render(tiny).includes(">$0.0000001</td>"),true);
is("channel scope excludes extras",records(data)[0].Definition.includes("exclude renewals and one-click extras"),true);
is("product scope includes extras",records(data)[1].Definition.includes("include one-click extras and exclude renewals"),true);
is("source data unchanged",data.channels[0].cents,1000);
done();
