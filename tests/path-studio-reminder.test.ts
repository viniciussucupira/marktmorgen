import type { PathRecord } from "@/lib/path";
import { pathStudioReminder } from "@/lib/path-studio-reminder";
import { localDay } from "@/lib/path-rules";
import { done, is, part } from "./check";
const now=Date.UTC(2026,9,19,12);
const record:PathRecord={answers:{goalCents:0,goalCurrency:"usd",skills:"",subject:"",minutes:15,audience:"none",timeZone:"UTC"},startedAt:now-86400000,checkins:["2026-10-18"],best:-1,bestAt:0,money:null,counts:null};
part("Studio reminders respect the owner, local day and quiet hours");
is("unopened day",pathStudioReminder(record,"owner",now),true);
for(const role of ["admin","editor","support"] as const) is(role,pathStudioReminder(record,role,now),false);
is("no Path",pathStudioReminder(null,"owner",now),false);
is("opened today",pathStudioReminder({...record,checkins:[localDay("UTC",now)]},"owner",now),false);
for(const hour of [0,7,21,23])is("quiet "+hour,pathStudioReminder(record,"owner",Date.UTC(2026,9,19,hour)),false);
is("Brazil morning",pathStudioReminder({...record,answers:{...record.answers,timeZone:"America/Sao_Paulo"}},"owner",now),true);
is("Tokyo quiet",pathStudioReminder({...record,answers:{...record.answers,timeZone:"Asia/Tokyo"}},"owner",now),false);
is("invalid zone",pathStudioReminder({...record,answers:{...record.answers,timeZone:"bad/zone"}},"owner",now),false);
is("future record",pathStudioReminder({...record,startedAt:now+1},"owner",now),false);
is("invalid time",pathStudioReminder(record,"owner",NaN),false);
is("recorded first sale",pathStudioReminder({...record,money:{at:now,test:false,real:1,cents:100,currency:"usd"}},"owner",now),false);
is("no check-in written",record.checkins,["2026-10-18"]);
done();
