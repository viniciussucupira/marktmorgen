import { adjacentCustomRange, presetCustomRange, type CustomRangePreset } from "@/lib/custom-range-dates";
import { CustomRangeResults, CustomRangePresets, CustomRange } from "@/components/custom-range";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const today="2026-10-15";
const period={from:"2026-10-01",to:"2026-10-07"};
part("Inclusive UTC periods move by their full duration");
is("previous week",adjacentCustomRange(period,-1,today),{from:"2026-09-24",to:"2026-09-30"});
is("next week",adjacentCustomRange(period,1,today),{from:"2026-10-08",to:"2026-10-14"});
is("one day moves once",adjacentCustomRange({from:"2026-10-14",to:"2026-10-14"},1,today),{from:today,to:today});
is("inverse move restores dates",adjacentCustomRange(adjacentCustomRange(period,-1,today)!,1,today),period);
is("leap day preserved",adjacentCustomRange({from:"2024-03-02",to:"2024-03-03"},-1,"2024-03-10"),{from:"2024-02-29",to:"2024-03-01"});
is("year boundary preserved",adjacentCustomRange({from:"2026-01-01",to:"2026-01-02"},-1,today),{from:"2025-12-30",to:"2025-12-31"});
is("UTC duration stays stable across clock changes",adjacentCustomRange({from:"2026-10-31",to:"2026-11-01"},1,"2026-11-10"),{from:"2026-11-02",to:"2026-11-03"});
part("Future and retained history limits never shorten a period");
is("future next week blocked",adjacentCustomRange({from:"2026-10-09",to:today},1,today),null);
is("today cannot move into tomorrow",adjacentCustomRange({from:today,to:today},1,today),null);
const earliest=new Date(Date.parse(today+"T00:00:00Z")-399*86400000).toISOString().slice(0,10);
is("retention boundary cannot move earlier",adjacentCustomRange({from:earliest,to:earliest},-1,today),null);
is("all retained days cannot move either way",[-1,1].map(d=>adjacentCustomRange({from:earliest,to:today},d as -1|1,today)),[null,null]);
for(const invalid of [{from:"2026-02-30",to:"2026-03-01"},{from:"bad",to:today},{from:today,to:"2026-10-01"},{from:"2024-01-01",to:"2024-01-02"},{from:today,to:"2026-10-16"}])is("invalid source period blocked",adjacentCustomRange(invalid,-1,today),null);
is("invalid today blocked",adjacentCustomRange(period,1,"wrong"),null);
part("Rendered controls respect availability and loading");
const zero={visitors:0,views:0,checkouts:0,sales:0,cents:0};
const data={...period,currency:"usd",totals:zero,before:null,days:[],channels:[],products:[],sales:"none",partial:false,elsewhere:0} as RangeData;
const render=(canPrevious:boolean,canNext:boolean,busy=false)=>renderToStaticMarkup(createElement(CustomRangeResults,{range:{...data,products:[]},marks:[],currency:"usd",onNavigate:()=>{},canPrevious,canNext,busy}));
const enabled=render(true,true);const blocked=render(false,false);const loading=render(true,true,true);
is("navigation group labeled",enabled.includes('role="group" aria-label="Move between periods"'),true);
is("both navigation buttons available",enabled.includes("Previous period")&&enabled.includes("Next period"),true);
is("unavailable navigation disabled",(blocked.match(/<button[^>]*disabled=""/g)??[]).length,2);
is("navigation disabled while reading",(loading.match(/<button[^>]*disabled=""/g)??[]).length,2);
is("available navigation enabled",/<button[^>]*disabled=""/.test(enabled),false);
part("Quick date ranges include today and follow the UTC calendar");
is("seven days includes today",presetCustomRange("7d",today),{from:"2026-10-09",to:today});
is("thirty days includes today",presetCustomRange("30d",today),{from:"2026-09-16",to:today});
is("ninety days includes today",presetCustomRange("90d",today),{from:"2026-07-18",to:today});
is("month begins on its first day",presetCustomRange("month",today),{from:"2026-10-01",to:today});
is("month first day stays one day",presetCustomRange("month","2026-01-01"),{from:"2026-01-01",to:"2026-01-01"});
is("leap February remains in UTC",presetCustomRange("30d","2024-03-01"),{from:"2024-02-01",to:"2024-03-01"});
is("year boundary stays inclusive",presetCustomRange("7d","2026-01-03"),{from:"2025-12-28",to:"2026-01-03"});
is("invalid date rejected",presetCustomRange("7d","2026-02-30"),null);
is("unknown shortcut rejected",presetCustomRange("bad" as CustomRangePreset,today),null);
const shortcuts=(busy=false,date=today)=>renderToStaticMarkup(createElement(CustomRangePresets,{today:date,busy,onSelect:()=>{}}));
const quick=shortcuts();
is("shortcuts form a labeled group",quick.includes('role="group" aria-label="Quick date ranges"'),true);
is("all four shortcuts visible",["Last 7 days","Last 30 days","Last 90 days","This month"].every(label=>quick.includes(label)),true);
is("shortcuts explicitly avoid form submission",(quick.match(/type="button"/g)??[]).length,4);
is("shortcuts enabled when idle",quick.includes('disabled=""'),false);
is("all shortcuts disabled while reading",(shortcuts(true).match(/disabled=""/g)??[]).length,4);
is("invalid calendar disables all shortcuts",(shortcuts(false,"bad").match(/disabled=""/g)??[]).length,4);
is("unfinished current day disclosed",quick.includes("include today in UTC")&&quick.includes("may still grow"),true);
is("shortcuts included in actual report form",renderToStaticMarkup(createElement(CustomRange,{today,currency:"usd"})).includes('aria-label="Quick date ranges"'),true);
done();
