import {createElement} from "react";
import {renderToStaticMarkup} from "react-dom/server";
import {PathCertificates} from "@/components/path-certificates";
import {PathShareCard} from "@/components/path-share-card";
import {done,is,part} from "./check";
const input={level:3,days:14,moneyCents:123400,currency:"usd",moneyAt:Date.UTC(2026,9,19),recordedAt:Date.UTC(2026,9,18)};
part("The existing share card has no private level certificate control");
const before=renderToStaticMarkup(createElement(PathShareCard,{input}));
is("canonical pre-change negative control",before.includes("Download certificate"),false);
const html=renderToStaticMarkup(createElement(PathCertificates,{input}));
is("certificate action is available",html.includes("Download certificate"),true);
is("native labeled reached-level choice",html.includes('for="path-certificate-level"')&&html.includes('<select'),true);
is("four saved levels",html.match(/<option /g)?.length,4);
is("money defaults off",html.includes("checked"),false);
is("amount absent from preview and fallback",html.includes("1,234"),false);
is("readonly accessible text fallback",html.includes('aria-describedby="path-certificate-help"')&&/readonly/i.test(html),true);
is("bounded extra server response",Buffer.byteLength(html,"utf8")<10000,true);
is("no level means no certificate section",renderToStaticMarkup(createElement(PathCertificates,{input:{...input,level:-1}})),"");
done();
