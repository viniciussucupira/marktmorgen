import {claimHandle,ensureStatsId} from "@/lib/store";
import {startPath,readPath,forgetPath,visitPath,pathIntroHash,returnMissionFor,pathJson,parsePath,PATH_SLOT} from "@/lib/path";
import {readAnswers} from "@/lib/path-rules";
import {dataBytes} from "@/lib/store-data-rules";
import {dataKey} from "@/lib/store-data";
import {redisPipeline} from "./redis-stub";
import {done,is,part} from "./check";
async function main(){
 const owner="pathreturn@example.com";await claimHandle(owner,"pathreturn","Path Return","Original introduction");
 const store=(await ensureStatsId(owner))!;
 const now=Date.UTC(2026,9,19,16),start=Date.UTC(2026,9,12,16);
 const read=readAnswers({goalCents:0,skills:"baking",subject:"bread",minutes:15,audience:"none",timeZone:"America/New_York"},store.currency);
 if(!read.ok)throw Error("answers");const answers=read.answers;
 await startPath(store,answers,start);
 const original=(await readPath(store))!;
 const legacy=pathJson(original);
 is("legacy has no invented return baseline",parsePath(legacy)?.returnStep,undefined);
 const first=await visitPath(store,original,now,async()=>false);
 const step=first.record.returnStep!;
 is("seven creator-local dates begin one welcome step",step,{day:"2026-10-19",introHash:pathIntroHash(store.bio)});
 is("current published introduction still pending",returnMissionFor(store,first.record,now)?.state,"open");
 is("opening never supplies a completion flag",JSON.stringify(step).includes("done"),false);
 is("raw introduction is not duplicated in Path",pathJson(first.record).includes("Original introduction"),false);
 is("strict round trip preserves private marker",parsePath(pathJson(first.record))?.returnStep,step);
 const reloaded=await visitPath(store,(await readPath(store))!,now+60000,async()=>false);
 is("reload keeps the original baseline",reloaded.record.returnStep,step);
 is("unchanged save never completes",returnMissionFor({...store,bio:store.bio+"   "},reloaded.record,now)?.state,"open");
 is("current empty introduction never completes",returnMissionFor({...store,bio:""},reloaded.record,now)?.state,"open");
 is("server-read updated own introduction completes",returnMissionFor({...store,bio:"Useful new introduction"},reloaded.record,now)?.state,"done");
 is("the unchanged own store remains pending",returnMissionFor(store,reloaded.record,now)?.state,"open");
 is("welcome step does not alter level",reloaded.record.best,original.best);
 const [room]=await redisPipeline([["HGET",dataKey(store)!,PATH_SLOT]]);
 is("existing room measures the changed record",Number(room),dataBytes(pathJson(reloaded.record)));
 is("private JSON fits the existing four KB read envelope",Buffer.byteLength(pathJson(reloaded.record))<4096,true);
 const raw=JSON.parse(pathJson(reloaded.record));raw.w={...step,done:true,person:"someone@example.test"};
 is("export parser retains no extra identity or completion",parsePath(JSON.stringify(raw))?.returnStep,step);
 raw.w.introHash="unhashed introduction";
 is("invalid baseline is discarded",parsePath(JSON.stringify(raw))?.returnStep,undefined);
 part("Existing CAS and answer edits preserve the private return baseline");
 await startPath(store,{...answers,subject:"Fresh subject"},now);
 const edited=(await readPath(store))!;
 is("answer edit preserves marker",edited.returnStep,step);
 await visitPath(store,original,now,async()=>false);
 is("stale first visit cannot replace saved answers",(await readPath(store))!.answers.subject,"Fresh subject");
 is("stale first visit cannot replace marker",(await readPath(store))!.returnStep,step);
 const next=await visitPath(store,(await readPath(store))!,now+86400000,async()=>false);
 is("next local day quietly retires the cue",returnMissionFor(store,next.record,now+86400000),null);
 const later=await visitPath({...store,bio:"A current introduction"},next.record,now+8*86400000,async()=>false);
 is("a later seven-date return gets one new factual baseline",later.record.returnStep,{day:"2026-10-27",introHash:pathIntroHash("A current introduction")});
 await forgetPath(store);
 is("forget removes the entire private return record",await readPath(store),null);
 const [remaining]=await redisPipeline([["HGET",dataKey(store)!,PATH_SLOT]]);
 is("forget releases its existing measured slot",Number(remaining??0),0);
 done();
}
main().catch(error=>{console.error(error);process.exit(1);});
