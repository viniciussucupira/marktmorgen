import {claimHandle,ensureStatsId} from "@/lib/store";
import {startPath,readPath,forgetPath,visitPath,PATH_SLOT} from "@/lib/path";
import {readAnswers} from "@/lib/path-rules";
import {dataKey} from "@/lib/store-data";
import {redisPipeline} from "./redis-stub";
import {done,is,part} from "./check";
async function main(){
 const owner="pathrace@example.com";await claimHandle(owner,"pathrace","Path Race","");
 const store=(await ensureStatsId(owner))!;
 const at=Date.UTC(2026,9,19,12),later=at+86_400_000;
 const read=readAnswers({goalCents:0,skills:"baking",subject:"bread",minutes:15,audience:"none",timeZone:"UTC"},store.currency);
 if(!read.ok)throw Error("answers");
 const answers=read.answers;
 part("An old visit cannot undo forgetting");
 await startPath(store,answers,at);
 const forgotten=(await readPath(store))!;
 await forgetPath(store);
 await visitPath(store,forgotten,later,async()=>false);
 is("a forgotten Path stays absent",await readPath(store),null);
 part("An old visit cannot lower a reached level");
 await forgetPath(store);await startPath(store,answers,at);
 const initial=(await readPath(store))!;
 const low={...initial,money:{at:later,test:false,real:0,cents:0,currency:store.currency},counts:{at:later,social:0,visitors:0,links:0,leads:0}};
 const high={...low,money:{...low.money,real:1,cents:10_000}};
 await visitPath(store,high,later,async()=>false);
 const reached=(await readPath(store))!.best;
 is("the higher reading reaches Morning",reached,2);
 await visitPath(store,low,later,async()=>false);
 is("a stale reading keeps the reached level",(await readPath(store))!.best,reached);
 part("An old visit cannot replace edited answers or their room");
 const beforeEdit=(await readPath(store))!;
 await startPath(store,{...answers,subject:"fresh subject"},later);
 const [roomBefore]=await redisPipeline([["HGET",dataKey(store)!,PATH_SLOT]]);
 await visitPath(store,beforeEdit,later+86_400_000,async()=>false);
 is("new answers stay saved",(await readPath(store))!.answers.subject,"fresh subject");
 const [roomAfter]=await redisPipeline([["HGET",dataKey(store)!,PATH_SLOT]]);
 is("refused stale writes leave the data room alone",roomAfter,roomBefore);
 part("A new start is a new record even when the old one was deleted");
 const fromOldStart=(await readPath(store))!;
 await forgetPath(store);await startPath(store,{...answers,subject:"new start"},later);
 await visitPath(store,fromOldStart,later+2*86_400_000,async()=>false);
 is("a stale visit cannot overwrite a restarted Path",(await readPath(store))!.answers.subject,"new start");
 done();
}
main().catch(error=>{console.error(error);process.exit(1);});
