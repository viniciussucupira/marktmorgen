import { customRangeComparison } from "@/lib/custom-range-comparison";
import { customRangeComparisonReport } from "@/lib/channel-reports";
import { CustomRangeComparison } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const name="Checkouts per 100 visitors";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,channels:[],products:[],days:[{date:"2026-10-01",visitors:15,views:25,checkouts:2,sales:1,cents:500},{date:"2026-10-02",visitors:15,views:25,checkouts:3,sales:1,cents:500}],totals:{visitors:20,views:50,checkouts:5,sales:2,cents:1000},before:{visitors:40,views:60,checkouts:4,sales:1,cents:800}};
const metric=(d:RangeData)=>customRangeComparison(d).rows.find(row=>row.name===name)!;
const csv=(d:RangeData)=>{const parsed=parseCsv(customRangeComparisonReport(d));const row=parsed.rows.find(row=>row[5]===name)!;return Object.fromEntries(parsed.header.map((key,i)=>[key,row[i]]));};
const render=(d:RangeData)=>renderToStaticMarkup(createElement(CustomRangeComparison,{range:d,currency:d.currency}));
const html=(d:RangeData)=>{const all=render(d);const start=all.indexOf(">"+name+"</th>");return all.slice(start,all.indexOf("</tr>",start));};
part("Compare checkout starts using each period's traffic");
is("current ratio uses consolidated visitors",metric(data).current,25);
is("previous ratio uses its own denominator",metric(data).previous,10);
is("difference uses checkout events per 100 visitors",metric(data).difference,15);
is("change is relative percentage growth",metric(data).change,150);
is("ratio is not monetary",[metric(data).money,metric(data).unit],[false,"Checkouts per 100 visitors"]);
is("daily visitor counts are not summed",metric({...data,days:[]}).current,25);
is("payments do not determine the ratio",metric({...data,totals:{...data.totals,sales:999,cents:999999}}).current,25);
is("page views do not determine denominator",metric({...data,totals:{...data.totals,views:999}}).current,25);
is("CSV exports analytical values",[csv(data).Current,csv(data).Previous,csv(data).Difference,csv(data)["Change (%)"]],["25","10","15","150"]);
is("JPY does not scale checkout counts",csv({...data,currency:"jpy"}).Current,"25");
is("KWD does not scale differences",csv({...data,currency:"kwd"}).Difference,"15");
is("UI displays signed difference",html(data).includes("+15"),true);
is("UI displays relative growth",html(data).includes("+150%"),true);
is("UI does not format the ratio as money",html(data).includes("$"),false);
part("Traffic remains independent of financial availability");
for(const d of [{...data,partial:true},{...data,sales:"none" as const},{...data,sales:"error" as const}]){
 is("checkout ratio survives unavailable payments",[metric(d).current,metric(d).previous,metric(d).difference,metric(d).change],[25,10,15,150]);
 is("CSV preserves traffic-based ratio",[csv(d).Current,csv(d)["Current available"]],["25","Yes"]);
 is("paid ratio still withheld",customRangeComparison(d).rows.find(row=>row.name==="Paid records per 100 visitors")?.current,null);
}
is("unknown previous financial values do not hide checkout ratio",metric({...data,before:{...data.before!,sales:null,cents:null}}).previous,10);
part("Zero activity and unavailable denominators");
const zeroCheckouts={...data,totals:{...data.totals,checkouts:0}};
is("zero checkouts with positive visitors is zero",metric(zeroCheckouts).current,0);
is("decline to zero is minus 100 percent",metric(zeroCheckouts).change,-100);
const zeroPrior={...data,before:{...data.before!,checkouts:0}};
is("zero prior ratio keeps absolute difference",metric(zeroPrior).difference,25);
is("zero prior ratio has no relative percentage",metric(zeroPrior).change,null);
const noVisitors={...data,totals:{...data.totals,visitors:0}};
is("no visitors is unavailable",metric(noVisitors).current,null);
is("no current denominator withholds changes",[metric(noVisitors).difference,metric(noVisitors).change],[null,null]);
is("known previous ratio remains visible",metric(noVisitors).previous,10);
is("unavailable ratio exports blank",[csv(noVisitors).Current,csv(noVisitors)["Current available"]],["","No"]);
is("no prior denominator remains unavailable",metric({...data,before:{...data.before!,visitors:0}}).previous,null);
is("missing history keeps current ratio",metric({...data,before:null}).current,25);
is("missing history does not become zero",[metric({...data,before:null}).previous,metric({...data,before:null}).difference],[null,null]);
is("missing previous ratio renders unavailable",html({...data,before:null}).includes("Unavailable"),true);
part("Repeated attempts and precise exports");
is("repeated attempts can exceed 100",metric({...data,totals:{...data.totals,checkouts:30}}).current,150);
const fractional={...data,totals:{...data.totals,checkouts:1,visitors:3}};
is("model keeps fractional precision",metric(fractional).current,1/3*100);
is("CSV keeps fractional precision",csv(fractional).Current,String(1/3*100));
for(const invalid of [-1,NaN,Infinity,1.5]) is("invalid checkout count unavailable",metric({...data,totals:{...data.totals,checkouts:invalid}}).current,null);
for(const invalid of [-1,NaN,Infinity,1.5]) is("invalid visitor count unavailable",metric({...data,totals:{...data.totals,visitors:invalid}}).current,null);
is("definition distinguishes events from buyers",csv(data).Definition.includes("It counts events, not distinct buyers or completed purchases"),true);
is("definition explains independent coverage",csv({...data,partial:true}).Definition.includes("It is independent of paid coverage"),true);
is("UI explains repeated attempts",render(data).includes("may exceed 100 after repeated attempts"),true);
is("source data remains unchanged",[data.totals.visitors,data.totals.checkouts,data.before!.checkouts],[20,5,4]);
done();
