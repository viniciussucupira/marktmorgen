import { paymentComparisonFrom, paymentChange, paymentShareChange } from "@/lib/payment-comparison";
import { PaymentComparisonPanel } from "@/components/payment-comparison";
import { paymentComparisonReport } from "@/lib/channel-reports";
import { numbersContext, SECTIONS } from "@/lib/numbers-ask";
import { channelsTool } from "@/lib/mcp-tools";
import type { StatsData } from "@/lib/stats";
import { parseCsv } from "@/lib/csv";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const now=Date.UTC(2026,9,13);
const date=(ago:number)=>new Date(now-ago*86400000).toISOString().slice(0,10);
const days=Array.from({length:90},(_,i)=>({date:date(89-i),visitors:0,views:0,checkouts:0,sales:0}));
const total={visitors:0,views:0,checkouts:0,sales:0,cents:0};
const data={sales:"ok",cashflowComplete:true,currency:"usd",days,totals:{d7:total,d30:total,d90:total,all:total},channels:{d7:[],d30:[],d90:[],all:[]},products:[],channelDays:{instagram:{[date(0)]:1000,[date(7)]:2000},google:{[date(0)]:2000},email:{[date(8)]:1000},direct:{[date(0)]:1000},outside:{[date(14)]:99999,[date(-1)]:99999}}} as unknown as StatsData;
part("Equal adjacent complete windows conserve both periods");
const report=paymentComparisonFrom(data,"d7")!;
is("exact current and previous UTC dates",[report.current.from,report.current.to,report.previous?.from,report.previous?.to],[date(6),date(0),date(13),date(7)]);
is("period totals exclude unrelated days",[report.current.total,report.previous?.total,report.delta],[4000,3000,1000]);
is("relative total change",report.change,1/3);
is("both period totals conserved in channel rows",[report.rows.reduce((n,r)=>n+r.current,0),report.rows.reduce((n,r)=>n+r.previous,0)],[4000,3000]);
const ig=report.rows.find(r=>r.source==="instagram")!;
is("same channel payment fall",[ig.current,ig.previous,ig.change],[1000,2000,-0.5]);
is("share uses each period denominator",[ig.currentShare,ig.previousShare],[0.25,2/3]);
is("share delta is percentage points",paymentShareChange(ig.shareChange),"-41.7 percentage points");
const google=report.rows.find(r=>r.source==="google")!;
is("current-only channel keeps zero prior payments but no growth percentage",[google.current,google.previous,google.change],[2000,0,null]);
const email=report.rows.find(r=>r.source==="email")!;
is("previous-only channel remains visible",[email.current,email.previous,email.change],[0,1000,-1]);
const month=paymentComparisonFrom({...data,channelDays:{instagram:{[date(0)]:10,[date(30)]:20,[date(60)]:99999}}},"d30")!;
is("thirty-day comparison boundaries",[month.previous?.from,month.previous?.to,month.current.total,month.previous?.total],[date(59),date(30),10,20]);
part("Absent prior periods and denominators are not zero comparisons");
const quarterly=paymentComparisonFrom(data,"d90")!;
is("ninety-day prior ledger unavailable",[quarterly.previous,quarterly.change,quarterly.delta,quarterly.rows],[null,null,null,[]]);
is("short history unavailable",paymentComparisonFrom({...data,days:days.slice(-13)},"d7")?.previous,null);
const gapDays=days.slice(-14).map((d,i)=>i===2 ? {...d,date:date(15)} : d);
is("nonconsecutive dates unavailable",paymentComparisonFrom({...data,days:gapDays},"d7")?.previous,null);
is("duplicate dates unavailable",paymentComparisonFrom({...data,days:[...days.slice(-14,-1),days[days.length-2]]},"d7")?.previous,null);
is("partial read unavailable",paymentComparisonFrom({...data,partial:true},"d7"),null);
is("missing ledger unavailable",paymentComparisonFrom({...data,channelDays:undefined},"d7"),null);
is("invalid prior amount unavailable",paymentComparisonFrom({...data,channelDays:{instagram:{[date(0)]:1000,[date(7)]:NaN}}},"d7")?.previous,null);
const noPrevious=paymentComparisonFrom({...data,channelDays:{instagram:{[date(0)]:1000}}},"d7")!;
is("complete prior zero is different from missing prior",[noPrevious.previous?.total,noPrevious.delta,noPrevious.change],[0,1000,null]);
is("share delta needs both denominators",noPrevious.rows[0].shareChange,null);
const noCurrent=paymentComparisonFrom({...data,channelDays:{instagram:{[date(7)]:1000}}},"d7")!;
is("zero current payments are a real complete fall",[noCurrent.current.total,noCurrent.change,noCurrent.rows[0].shareChange],[0,-1,null]);
is("zero both periods do not invent change",paymentComparisonFrom({...data,channelDays:{}},"d7")?.change,null);
is("no infinity and no relative vs point confusion",[paymentChange(null),paymentChange(0.5),paymentShareChange(0.1)],["No previous payments","+50.0%","+10.0 percentage points"]);
part("Export and interface keep money, dates and coverage");
const rows=parseCsv(paymentComparisonReport(report,"usd")).rows;
const igCsv=rows.find(r=>r[5]==="instagram")!;
is("dates and amounts exported",igCsv.slice(0,10),[date(6),date(0),date(13),date(7),"USD","instagram","10","20","-10","-50"]);
is("prior-zero change is blank",rows.find(r=>r[5]==="google")?.[9],"");
is("missing comparison exports no fake rows",parseCsv(paymentComparisonReport(quarterly,"usd")).rows.length,0);
is("yen minor units retained",parseCsv(paymentComparisonReport(report,"jpy")).rows.find(r=>r[5]==="instagram")?.[6],"1000");
is("three decimal currency",parseCsv(paymentComparisonReport(report,"kwd")).rows.find(r=>r[5]==="instagram")?.[6],"1");
is("formula channel protected",parseCsv(paymentComparisonReport({...report,rows:[{...ig,source:"=1+1"}]},"usd")).rows[0][5],"'=1+1");
const render=(value:StatsData,range:"d7"|"d30"|"d90"="d7")=>renderToStaticMarkup(createElement(PaymentComparisonPanel,{data:value,range}));
const html=render(data);
is("download and prior-only channel",html.includes("Download payment comparison") && html.includes("Email"),true);
is("scope and units explained",html.includes("as recorded so far") && html.includes("percentage points") && html.includes("not new customers"),true);
is("unavailable prior has no download",[render(data,"d90").includes("previous period is not available"),render(data,"d90").includes("Download payment comparison")],[true,false]);
is("partial component absent",render({...data,partial:true}),"");
part("Assistant and tools retain exact previous coverage");
const context=numbersContext(data).last_7_days as {payment_comparison:{previous_available:boolean;previous_period:{payments:string};difference:string}};
is("assistant exact baseline and delta",[context.payment_comparison.previous_available,context.payment_comparison.previous_period.payments,context.payment_comparison.difference],[true,"$30","$10"]);
is("assistant prior unavailable is null",(numbersContext(data).last_90_days as {payment_comparison:{previous_period:unknown}}).payment_comparison.previous_period,null);
is("assistant section supported",SECTIONS.includes("payment-comparison"),true);
const tool=channelsTool(data,"d7");
is("tool amounts in minor units",[tool.payment_comparison?.difference,tool.payment_comparison?.previous_period?.payments],[1000,3000]);
is("tool partial unavailable",channelsTool({...data,partial:true},"d7").payment_comparison,null);
is("no customer identities in comparison",/receipt_email|customer_details|@example.com/.test(JSON.stringify(tool.payment_comparison)),false);
done();
