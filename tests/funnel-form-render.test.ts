import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { FunnelFormSetup } from "@/components/funnel-form-setup";
import { MAX_FIELDS } from "@/lib/forms";
import { done, is, part } from "./check";
part("Guided form questions expose consent and bounds");
const render = (fields: {type:"short"|"long"|"email";label:string;required:boolean}[], offerList=false) => renderToStaticMarkup(createElement(FunnelFormSetup,{value:{fields,offerList},onChange(){}}));
const short=render([{type:"short",label:"Project <details>",required:true}]);
const opt=(html:string)=>(html.match(/<input[^>]*type="checkbox"[^>]*>/g)??[]).at(-1)??"";
is("subscription is unavailable without an email question",opt(short).includes('disabled=""'),true);
is("a single question cannot be removed",/<button[^>]*disabled=""[^>]*aria-label="Remove question 1"/.test(short),true);
is("author text is escaped",short.includes("Project &lt;details&gt;"),true);
const email=render([{type:"email",label:"Email",required:true}]);
is("an email question permits an optional offer",opt(email).includes("disabled"),false);
is("the optional offer is not selected by default",opt(email).includes("checked"),false);
is("explicitly selected offers are visible",opt(render([{type:"email",label:"Email",required:false}],true)).includes('checked=""'),true);
const full=render(Array.from({length:MAX_FIELDS},()=>({type:"short" as const,label:"Question",required:false})));
is("the add button stops at the published question cap",/<button[^>]*disabled=""[^>]*>Add question<\/button>/.test(full),true);
is("consent and confirmation are explained",email.includes("Visitors choose whether to subscribe and must confirm their email."),true);
done();
