import { CustomRangeResults } from "@/components/custom-range";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const range={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:true,elsewhere:0,totals:{visitors:50,views:100,checkouts:10,sales:2,cents:99900},before:{visitors:25,views:50,checkouts:5,sales:1,cents:5000},days:[{date:"2026-10-01",visitors:30,views:60,checkouts:6,sales:1,cents:50000},{date:"2026-10-02",visitors:20,views:40,checkouts:4,sales:1,cents:49900}],channels:[{source:"google",visits:50,sales:2,cents:99900}],products:[{id:"guide",title:"Guide",views:100,checkouts:10,sales:2,cents:99900}]} as RangeData & {products:(RangeData["products"][number]&{title:string})[]};
const render=(snapshot:typeof range)=>renderToStaticMarkup(createElement(CustomRangeResults,{range:snapshot,marks:[{day:"2026-10-01",kind:"product",text:"Launch day"}],currency:"usd"}));
const tile=(html:string,label:string)=>{const start=html.indexOf(">"+label+"</dt>");return start<0?null:html.slice(start,html.indexOf("</div>",start));};
part("Incomplete paid readings cannot appear as complete results");
const partial=render(range);
is("partial notice explains unavailable money",partial.includes("Sales and revenue are unavailable"),true);
is("partial sales tile absent",tile(partial,"Sales"),null);
is("partial revenue tile absent",tile(partial,"Revenue"),null);
is("partial channel and product money absent",partial.includes("$999"),false);
is("partial channel paid headings absent",partial.includes(">Sales</th>")||partial.includes(">Revenue</th>"),false);
is("partial chart title excludes paid count",/title="[^"]*, 1 sales/.test(partial),false);
is("current traffic remains",tile(partial,"Visitors")?.includes(">50</dd>"),true);
is("current views remain",tile(partial,"Page views")?.includes(">100</dd>"),true);
is("current checkouts remain",tile(partial,"Checkouts started")?.includes(">10</dd>"),true);
is("confirmed traffic comparison remains",tile(partial,"Visitors")?.includes("+100%"),true);
is("channel visits remain",partial.includes("Google")&&partial.includes(">50</td>"),true);
is("product views remain",partial.includes("Guide")&&partial.includes(">100</td>"),true);
is("marks remain",partial.includes("Launch day"),true);
part("Confirmed and unavailable paid readings");
const complete=render({...range,partial:false});
is("complete sales tile present",tile(complete,"Sales")?.includes(">2</dd>"),true);
is("complete money remains",tile(complete,"Revenue")?.includes("$999"),true);
is("complete comparison remains",tile(complete,"Revenue")?.includes("+1898%"),true);
is("complete table paid headings remain",complete.includes(">Sales</th>")&&complete.includes(">Revenue</th>"),true);
is("complete daily paid counts remain",/title="[^"]*, 1 sales/.test(complete),true);
for(const sales of ["none","error"] as const){const html=render({...range,partial:false,sales});is(sales+" has no money",html.includes("$999"),false);is(sales+" keeps traffic",tile(html,"Visitors")?.includes(">50</dd>"),true);}
is("reading failure message remains",render({...range,partial:false,sales:"error"}).includes("Stripe did not answer"),true);
is("confirmed zero paid totals remain zero",tile(render({...range,partial:false,totals:{...range.totals,sales:0,cents:0}}),"Sales")?.includes(">0</dd>"),true);
is("rendering does not mutate source",range.totals.cents,99900);
done();
