import { customRangeView, customRangeOrderLabel, effectiveCustomRangeSort } from "@/lib/custom-range-view";
import { customRangeChannelsReport, customRangeProductsReport } from "@/lib/channel-reports";
import { CustomRangeResults } from "@/components/custom-range";
import type { RangeData } from "@/lib/stats";
import { parseCsv } from "@/lib/csv";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const data={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,days:[],totals:{visitors:30,views:60,checkouts:6,sales:3,cents:3000},before:null,channels:[{source:"google",visits:20,sales:1,cents:1000},{source:"email",visits:10,sales:2,cents:2000}],products:[{id:"guide",title:"Café Guide",views:40,checkouts:4,sales:1,cents:1000},{id:"course",title:"Email Course",views:20,checkouts:2,sales:2,cents:2000}]} as Omit<RangeData,"products"> & {products:(RangeData["products"][number]&{title:string})[]};
const channels=(sort:Parameters<typeof customRangeView>[2])=>customRangeView(data,"",sort).channels.map(r=>r.source);
const products=(sort:Parameters<typeof customRangeView>[2])=>customRangeView(data,"",sort).products.map(r=>r.id);
const first=(csv:string,key:string)=>{const p=parseCsv(csv);return p.rows[0][p.header.indexOf(key)];};
part("Sorts operate on copies and match exported order");
is("traffic descending",channels("traffic_desc"),["google","email"]);
is("traffic ascending",channels("traffic_asc"),["email","google"]);
is("revenue descending",channels("revenue_desc"),["email","google"]);
is("revenue ascending",channels("revenue_asc"),["google","email"]);
is("paid records descending",products("sales_desc"),["course","guide"]);
is("paid records ascending",products("sales_asc"),["guide","course"]);
is("product traffic ascending",products("traffic_asc"),["course","guide"]);
is("names use display labels",channels("name"),["email","google"]);
is("accented product names ordered normally",products("name"),["guide","course"]);
is("search precedes sorting",customRangeView(data,"email","revenue_desc").products.map(r=>r.id),["course"]);
is("source order unchanged",data.channels.map(r=>r.source),["google","email"]);
is("totals remain whole-period",customRangeView(data,"email","revenue_desc").totals,data.totals);
const ordered=customRangeView(data,"","revenue_desc");
is("channel CSV first row matches display",first(customRangeChannelsReport(ordered,{sort:"revenue_desc"}),"Channel"),"Email");
is("CSV records effective revenue ordering",first(customRangeChannelsReport(ordered,{sort:"revenue_desc"}),"Order"),"Revenue, highest first");
is("product CSV first row matches display",first(customRangeProductsReport(ordered,{sort:"revenue_desc"}),"Product"),"Email Course");
part("Unknown paid values cannot control ordering");
for(const snapshot of [{...data,partial:true},{...data,sales:"error" as const},{...data,sales:"none" as const}]){
 const selected=customRangeView(snapshot,"","revenue_desc");
 is("unknown revenue falls back to traffic",selected.channels.map(r=>r.source),["google","email"]);
 is("unknown sales fall back to traffic",customRangeView(snapshot,"","sales_asc").products.map(r=>r.id),["guide","course"]);
 is("effective choice disclosed",effectiveCustomRangeSort(snapshot,"revenue_desc"),"traffic_desc");
 is("CSV does not claim unknown revenue order",first(customRangeChannelsReport(selected,{sort:"revenue_desc"}),"Order"),"Visits, highest first");
}
is("invalid choice returns recorded order",effectiveCustomRangeSort(data,"invented"),"recorded");
is("product traffic label is specific",customRangeOrderLabel(data,"traffic_asc","products"),"Page views, lowest first");
const html=renderToStaticMarkup(createElement(CustomRangeResults,{range:{...data,partial:true},marks:[],currency:"usd"}));
is("sort has accessible label",html.includes('for="range-sort"'),true);
is("unavailable financial options disabled",html.includes('value="revenue_desc" disabled=""')&&html.includes('value="sales_desc" disabled=""'),true);
done();
