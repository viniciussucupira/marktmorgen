import { funnelRepairActions } from "@/lib/funnel-review-actions";
import { done, is, part } from "./check";
part("Funnel corrections preserve permissions and selected store");
const actions = funnelRepairActions({ sid: "store-a" }, "owner");
is("all owner destinations keep the store", actions.every(a => a.href.includes("store=store-a")), true);
is("anchors stay after the store query", actions.map(a => a.href), ["/studio?store=store-a#products", "/studio/site?store=store-a", "/studio?store=store-a#stripe", "/studio?store=store-a#billing"]);
is("editor cannot be guided to payment changes", funnelRepairActions({ sid: "store-a" }, "editor").map(a => a.label), ["Review products and delivery", "Review your pages"]);
is("admin cannot be guided to plan or connection changes", funnelRepairActions({ sid: "store-a" }, "admin").length, 2);
is("support has no editing destinations", funnelRepairActions({ sid: "store-a" }, "support"), []);
is("second store stays selected", funnelRepairActions({ sid: "store-b" }, "owner").every(a => a.href.includes("store=store-b") && !a.href.includes("store-a")), true);
is("legacy store has no empty query", funnelRepairActions({ sid: "" }, "owner")[0].href, "/studio#products");
done();
