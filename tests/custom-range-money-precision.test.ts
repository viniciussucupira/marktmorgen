import { CustomRangeComparison } from "@/components/custom-range";
import { customRangeComparison } from "@/lib/custom-range-comparison";
import { customRangeComparisonReport } from "@/lib/channel-reports";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,channels:[],products:[],days:[],totals:{visitors:1000000,views:1000000,checkouts:1,sales:1000000,cents:1},before:{visitors:2000000,views:2000000,checkouts:1,sales:2000000,cents:1}};
const names=["Revenue per visitor","Revenue per paid record"];
const render=(d:RangeData)=>renderToStaticMarkup(createElement(CustomRangeComparison,{range:d,currency:d.currency}));
const cells=(d:RangeData,name:string)=>{const html=render(d),start=html.indexOf('>'+name+'</th>'),row=html.slice(start,html.indexOf('</tr>',start));return [...row.matchAll(/<td[^>]*>(.*?)<\/td>/g)].map(m=>m[1]);};
const csv=(d:RangeData,name:string)=>{const p=parseCsv(customRangeComparisonReport(d)),r=p.rows.find(row=>row[5]===name)!;return Object.fromEntries(p.header.map((key,i)=>[key,r[i]]));};
part("Tiny monetary averages and differences keep their magnitude and sign");
for(const name of names){
 is(name+" small positive values",cells(data,name),["$0.00000001","$0.000000005","+$0.000000005","+100%"]);
 const decline={...data,totals:{...data.totals,visitors:4000000,sales:4000000}};
 is(name+" small negative difference",cells(decline,name).slice(0,3),["$0.0000000025","$0.000000005","-$0.0000000025"]);
 is(name+" JPY magnitude",cells({...data,currency:"jpy"},name)[0],"¥0.000001");
 is(name+" KWD magnitude",cells({...data,currency:"kwd"},name)[0],"KWD 0.000000001");
 is(name+" CSV retains exact analytical value",csv(data,name).Current,String((1/1000000)/100));
 is(name+" model remains unrounded",customRangeComparison(data).rows.find(r=>r.name===name)!.current,1/1000000);
 const zero={...data,totals:{...data.totals,cents:0},before:{...data.before!,cents:0}};
 is(name+" true zero stays zero",cells(zero,name),["$0","$0","$0","—"]);
 is(name+" absent history stays unavailable",cells({...data,before:null},name).slice(1),["Unavailable","Unavailable","—"]);
 for(const d of [{...data,partial:true},{...data,sales:"error" as const},{...data,sales:"none" as const}])is(name+" incomplete money withheld",cells(d,name),["Unavailable","Unavailable","Unavailable","—"]);
}
part("Normal money keeps its established presentation");
const ordinary={...data,totals:{...data.totals,cents:123456,visitors:1,sales:1}};
is("gross revenue unchanged",cells(ordinary,"Gross revenue")[0],"$1,234.56");
is("ordinary revenue per visitor unchanged",cells(ordinary,names[0])[0],"$1,234.56");
is("ordinary revenue per paid record unchanged",cells(ordinary,names[1])[0],"$1,234.56");
const unit={...data,totals:{...data.totals,cents:1,visitors:1,sales:1}};
is("one minor unit uses ordinary format",cells(unit,names[0])[0],"$0.01");
const fraction={...data,totals:{...data.totals,cents:100,visitors:3,sales:3}};
is("normal fractional average still currency rounded",cells(fraction,names[0])[0],"$0.33");
is("normal fractional CSV unchanged",csv(fraction,names[0]).Current,String((100/3)/100));
is("policy explained in UI",render(data).includes("very small nonzero monetary values remain visible with up to four significant digits"),true);
done();
