import { customRangeComparison } from "@/lib/custom-range-comparison";
import { customRangeComparisonReport } from "@/lib/channel-reports";
import { CustomRangeComparison } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const name="Page views per visitor";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,channels:[],products:[],days:[{date:"2026-10-01",visitors:80,views:100,checkouts:0,sales:0,cents:0},{date:"2026-10-02",visitors:80,views:150,checkouts:0,sales:0,cents:0}],totals:{visitors:100,views:250,checkouts:0,sales:0,cents:0},before:{visitors:50,views:100,checkouts:0,sales:0,cents:0}};
const metric=(d:RangeData)=>customRangeComparison(d).rows.find(row=>row.name===name)!;
const csv=(d:RangeData)=>{const p=parseCsv(customRangeComparisonReport(d)),row=p.rows.find(row=>row[5]===name)!;return Object.fromEntries(p.header.map((key,i)=>[key,row[i]]));};
const render=(d:RangeData)=>renderToStaticMarkup(createElement(CustomRangeComparison,{range:d,currency:d.currency}));
const cells=(d:RangeData)=>{const html=render(d),start=html.indexOf('>'+name+'</th>'),row=html.slice(start,html.indexOf('</tr>',start));return [...row.matchAll(/<td[^>]*>(.*?)<\/td>/g)].map(m=>m[1]);};
part("Period browsing ratio uses visitor estimates, independently of payments");
is("selected period ratio",metric(data).current,2.5);
is("previous ratio",metric(data).previous,2);
is("absolute difference in views per visitor",metric(data).difference,0.5);
is("relative percentage change",metric(data).change,25);
is("ratio is not an average or sum of daily visitor ratios",metric(data).current===250/160,false);
is("rendered comparison",cells(data),["2.5","2","+0.5","+25%"]);
is("non-monetary analytical metric",[metric(data).money,metric(data).ratio,metric(data).unit],[false,true,"Views per visitor"]);
for(const d of [{...data,partial:true},{...data,sales:"error" as const},{...data,sales:"none" as const},{...data,before:{...data.before!,sales:null,cents:null}}]){
 is("unavailable payments do not hide browsing",metric(d).current,2.5);
 is("unknown payments preserve comparison",metric(d).previous,2);
}
part("Zeros and missing history remain distinct");
is("no current visitors is unavailable",metric({...data,totals:{...data.totals,visitors:0}}).current,null);
is("no prior visitors is unavailable",metric({...data,before:{...data.before!,visitors:0}}).previous,null);
is("missing prior traffic remains unavailable",cells({...data,before:null}).slice(1),["Unavailable","Unavailable","—"]);
is("confirmed zero views with visitors is zero",metric({...data,totals:{...data.totals,views:0}}).current,0);
is("zero prior ratio has no percentage",metric({...data,before:{...data.before!,views:0}}).change,null);
for(const visitors of [-1,0.5,NaN,Infinity,Number.MAX_SAFE_INTEGER+1])is("invalid visitor denominator rejected",metric({...data,totals:{...data.totals,visitors}}).current,null);
for(const views of [-1,0.5,NaN,Infinity,Number.MAX_SAFE_INTEGER+1])is("invalid view count rejected",metric({...data,totals:{...data.totals,views}}).current,null);
part("CSV preserves precision and explains the aggregate meaning");
const fraction={...data,totals:{...data.totals,visitors:3,views:1}};
is("fraction not rounded in model",metric(fraction).current,1/3);
is("display rounds analytical ratio",cells(fraction)[0],"0.3333");
is("CSV keeps full precision",csv(fraction).Current,String(1/3));
is("CSV unit independent of currency",csv({...fraction,currency:"jpy"}).Unit,"Views per visitor");
is("CSV previous ratio",csv(data).Previous,"2");
is("CSV absolute difference",csv(data).Difference,"0.5");
is("CSV relative percent",csv(data)["Change (%)"],"25");
is("CSV missing reading blank",csv({...data,before:null}).Previous,"");
is("CSV zero denominator blank",csv({...data,totals:{...data.totals,visitors:0}}).Current,"");
is("CSV missing availability explicit",csv({...data,before:null})["Previous available"],"No");
is("definition avoids session claim",metric(data).definition.includes("not pages per session"),true);
is("definition explains repeated views",metric(data).definition.includes("Repeated views count"),true);
is("definition visible in UI",render(data).includes(metric(data).definition),true);
is("definition in CSV",csv(data).Definition.includes(metric(data).definition),true);
const tiny={...data,totals:{...data.totals,visitors:10000000,views:1}};
is("rare views stay nonzero",cells(tiny)[0],"0.0000001");
is("source data unchanged",[data.totals.visitors,data.totals.views],[100,250]);
done();
