import { selectedRevenueShare, formatSelectedRevenueShare } from "@/lib/custom-range-efficiency";
import { customRangeChannelsReport, customRangeProductsReport } from "@/lib/channel-reports";
import { customRangeView } from "@/lib/custom-range-view";
import { CustomRangeResults } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,before:null,days:[],totals:{visitors:999,views:999,sales:999,checkouts:999,cents:999999},channels:[{source:"email",visits:10,sales:1,cents:1000},{source:"google",visits:30,sales:3,cents:3000},{source:"zero",visits:5,sales:0,cents:0}],products:[{id:"email",views:10,checkouts:1,sales:1,cents:2000},{id:"google",views:30,checkouts:3,sales:3,cents:3000},{id:"zero",views:5,checkouts:0,sales:0,cents:0}],channelsTotal:100,channelsTruncated:true,productsTotal:120,productsTruncated:true};
const records=(text:string)=>{const p=parseCsv(text);return p.rows.map(row=>Object.fromEntries(p.header.map((key,i)=>[key,row[i]])));};
const shares=(d:RangeData)=>[records(customRangeChannelsReport(d)).map(r=>r["Share of selected revenue (%)"]),records(customRangeProductsReport(d)).map(r=>r["Share of selected revenue (%)"])];
const render=(range:RangeData)=>renderToStaticMarkup(createElement(CustomRangeResults,{range:{...range,products:range.products.map(p=>({...p,title:p.id}))},marks:[],currency:range.currency}));
part("Shares describe each selected loaded list, not the whole period");
is("channel shares use loaded channel revenue",shares(data)[0],["25","75","0"]);
is("product shares preserve their extra scope",shares(data)[1],["40","60","0"]);
is("whole-period totals do not affect shares",shares({...data,totals:{...data.totals,cents:1}}),shares(data));
is("currency cancels out",shares({...data,currency:"jpy"}),shares(data));
is("table labels explicit",(render(data).match(/>Share of selected revenue<\/th>/g)??[]).length,2);
is("channel shares visible",render(data).includes(">25%</td>")&&render(data).includes(">75%</td>"),true);
is("product shares visible",render(data).includes(">40%</td>")&&render(data).includes(">60%</td>"),true);
is("zero share is numeric zero",render(data).includes(">0%</td>"),true);
is("selection basis explained",render(data).includes("not whole-period revenue"),true);
is("loaded limit explained",render(data).includes("limited lists describe only the loaded selection"),true);
for(const report of [customRangeChannelsReport(data),customRangeProductsReport(data)]){
 const rows=records(report);
 is("export warns about loaded scope",rows.every(r=>r.Definition.includes("percentages describe only loaded rows even when truncated")),true);
 is("source limit remains explicit",rows[0]["List truncated"],"Yes");
}
part("Search, minimums and ordering preserve the correct denominator");
is("search reweights each selected list",shares(customRangeView(data,"email")),[["100"],["100"]]);
is("minimum traffic reweights each selected list",shares(customRangeView(data,"","recorded","all",20)),[["100"],["100"]]);
is("minimum paid records reweights each selected list",shares(customRangeView(data,"","recorded","all",0,2)),[["100"],["100"]]);
is("sorting preserves per-row share",shares(customRangeView(data,"","revenue_desc")),[["75","25","0"],["60","40","0"]]);
is("unconverted selection with no revenue is unavailable",shares(customRangeView(data,"","recorded","unconverted")),[[""],[""]]);
part("Unavailable payments and zero total do not become percentages");
const zero={...data,channels:data.channels.map(r=>({...r,cents:0})),products:data.products.map(r=>({...r,cents:0}))};
is("zero total has no shares",shares(zero),[["","",""],["","",""]]);
is("zero total shown unavailable",render(zero).includes(">Unavailable</td>"),true);
for(const d of [{...data,partial:true},{...data,sales:"none" as const},{...data,sales:"error" as const}]){
 is("unknown shares blank",shares(d),[["","",""],["","",""]]);
 is("unknown share columns hidden",render(d).includes(">Share of selected revenue</th>"),false);
 is("observed visits preserved",records(customRangeChannelsReport(d))[0].Visits,"10");
}
is("missing denominator remains unavailable",selectedRevenueShare(100,null,true),null);
is("unknown money cannot calculate share",selectedRevenueShare(100,200,false),null);
is("zero total unavailable",selectedRevenueShare(0,0,true),null);
is("negative revenue rejected",selectedRevenueShare(-1,100,true),null);
is("revenue above selected total rejected",selectedRevenueShare(101,100,true),null);
is("unsafe total rejected",selectedRevenueShare(1,Number.MAX_SAFE_INTEGER+1,true),null);
part("Display rounding does not alter analytical exports");
is("fractional share computed before formatting",selectedRevenueShare(1,3,true),1/3*100);
is("four significant digits displayed",formatSelectedRevenueShare(selectedRevenueShare(1,3,true)),"33.33%");
is("rare share stays nonzero",formatSelectedRevenueShare(selectedRevenueShare(1,100000000,true)),"0.000001%");
is("unavailable formatter",formatSelectedRevenueShare(null),"Unavailable");
const fraction={...data,channels:[{source:"one",visits:1,sales:1,cents:1},{source:"two",visits:1,sales:1,cents:2}]};
is("CSV retains fractional precision",shares(fraction)[0][0],String(1/3*100));
is("source rows not mutated",data.channels[0].cents,1000);
done();
