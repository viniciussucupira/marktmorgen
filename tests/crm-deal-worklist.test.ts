import { dealOrder, orderDeals, dealWorklistCsv, dealWorklistRows } from "@/lib/crm-deal-worklist";
import { parseCsv } from "@/lib/csv";
import { DEFAULT_STAGES, type Deal } from "@/lib/crm-rules";
import { filterDeals } from "@/lib/crm-deal-filter";
import { done, is, part } from "./check";
const a: Deal = { id: "aaaaaaaaaa", title: "Later", email: "a@example.com", cents: 500, stage: "lead00", note: "", nextAction: "Call", dueDate: "2026-10-18", updatedAt: 20, createdAt: 1 };
const b: Deal = { ...a, id: "bbbbbbbbbb", title: "Soon", cents: 900, dueDate: "2026-10-17", updatedAt: 30, assignee: "owner@example.com" };
const c: Deal = { ...a, id: "cccccccccc", title: "=SUM(1,2)", email: "", cents: 700, stage: "won000", dueDate: "", updatedAt: 10, note: 'Line one\n"Line two"', nextAction: "@review" };
const rows = [a, b, c];
const ids = (order: Parameters<typeof orderDeals>[1]) => orderDeals(rows, order).map(row => row.id);
part("CRM worklist priority and export");
is("current order preserved", ids("current"), [a.id, b.id, c.id]);
is("earliest real date first, missing last", ids("due"), [b.id, a.id, c.id]);
is("highest estimate first", ids("value"), [b.id, c.id, a.id]);
is("longest unchanged first", ids("oldest"), [c.id, a.id, b.id]);
is("original array unchanged", rows.map(row => row.id), [a.id, b.id, c.id]);
is("current returns a distinct array", orderDeals(rows, "current") === rows, false);
is("invalid option falls back", [null, "constructor", ["due"], "DUE"].map(dealOrder), ["current", "current", "current", "current"]);
is("valid options", ["due", "value", "oldest", "current"].map(dealOrder), ["due", "value", "oldest", "current"]);
const invalid = { ...b, dueDate: "2026-02-30", updatedAt: 0 };
is("missing date follows even the last valid calendar date", orderDeals([{ ...c, updatedAt: 1 }, { ...a, dueDate: "9999-12-31" }], "due").map(row => row.id), [a.id, c.id]);
is("invalid date follows confirmed date", orderDeals([invalid, a], "due").map(row => row.id), [a.id, b.id]);
is("missing update follows known update", orderDeals([invalid, a], "oldest").map(row => row.id), [a.id, b.id]);
is("tied priorities use stable id", orderDeals([{ ...a, id: b.id }, a], "value").map(row => row.id), [a.id, b.id]);
is("filters compose before priority", orderDeals(filterDeals(rows, "soon", "owner@example.com"), "due").map(row => row.id), [b.id]);
const context = { today: "2026-10-17", currency: "usd", query: "=search", responsible: "all", filter: "all", order: "value" as const };
const csv = parseCsv(dealWorklistCsv(orderDeals(rows, "value"), DEFAULT_STAGES, context));
const at = (row: number, name: string) => csv.rows[row][csv.header.indexOf(name)];
is("CSV mirrors stage columns then chosen row order", csv.rows.map(row => row[0]), [b.id, a.id, c.id]);
is("CSV retains full estimate in cents", at(0, "stored_value_cents"), "900");
is("currency explicit", at(0, "currency"), "USD");
is("query formula is text", at(0, "search"), "'=search");
is("title formula is text", at(2, "title"), "'=SUM(1,2)");
is("action formula is text", at(2, "next_action"), "'@review");
is("quoted multiline note round trips", at(2, "note"), c.note);
is("date is UTC calendar, not shifted", at(0, "due_date_utc"), "2026-10-17");
is("scope explicit", at(0, "scope"), "loaded_selected_deals");
is("value is not revenue", at(0, "value_definition"), "Stored opportunity estimate; not confirmed revenue");
is("only supplied selection exported", parseCsv(dealWorklistCsv([b], DEFAULT_STAGES, context)).rows.length, 1);
is("empty selection retains just header", parseCsv(dealWorklistCsv([], DEFAULT_STAGES, context)).rows, []);
const cross = { ...a, id: "dddddddddd", title: "Earlier in another stage", stage: "talk00", dueDate: "2026-10-15", cents: 1200 };
const ordered = orderDeals([a, b, cross], "due");
is("agenda row order crosses stage boundaries", dealWorklistRows(ordered, DEFAULT_STAGES, "agenda").map(row => row.deal.id), [cross.id, b.id, a.id]);
is("board retains stage grouping", dealWorklistRows(ordered, DEFAULT_STAGES, "board").map(row => row.deal.id), [b.id, a.id, cross.id]);
const agendaCsv = parseCsv(dealWorklistCsv(ordered, DEFAULT_STAGES, { ...context, order:"due", view:"agenda" }));
is("agenda CSV follows displayed global order", agendaCsv.rows.map(row => row[0]), [cross.id, b.id, a.id]);
is("agenda export identifies view", agendaCsv.rows.map(row => row[agendaCsv.header.indexOf("view")]), ["agenda","agenda","agenda"]);
is("board export identifies default view", at(0,"view"), "board");
is("export retains real stage on global rows", agendaCsv.rows[0][agendaCsv.header.indexOf("stage")], "Talking");
is("filtered agenda exports only selected contact", parseCsv(dealWorklistCsv(filterDeals(ordered,"soon",null), DEFAULT_STAGES, {...context,view:"agenda"})).rows.map(row=>row[0]), [b.id]);
is("unknown stages excluded consistently", dealWorklistRows([{...a,stage:"gone"}],DEFAULT_STAGES,"agenda"), []);
is("unknown stages excluded from CSV", parseCsv(dealWorklistCsv([{...a,stage:"gone"}],DEFAULT_STAGES,{...context,view:"agenda"})).rows, []);
is("row projection preserves input order and identities", [ordered.map(row=>row.id),dealWorklistRows(ordered,DEFAULT_STAGES,"agenda")[0].deal===cross], [[cross.id,b.id,a.id],true]);
done();
