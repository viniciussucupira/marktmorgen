import { customRangeComparison } from "@/lib/custom-range-comparison";
import { customRangeComparisonReport } from "@/lib/channel-reports";
import { CustomRangeComparison } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const name="Revenue per visitor";
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,channels:[],products:[],days:[{date:"2026-10-01",visitors:15,views:20,checkouts:2,sales:1,cents:1000},{date:"2026-10-02",visitors:15,views:30,checkouts:3,sales:2,cents:10000}],totals:{visitors:20,views:50,checkouts:5,sales:3,cents:11000},before:{visitors:40,views:60,checkouts:10,sales:5,cents:10000}};
const metric=(d:RangeData)=>customRangeComparison(d).rows.find(row=>row.name===name)!;
const csv=(d:RangeData)=>{const parsed=parseCsv(customRangeComparisonReport(d));const row=parsed.rows.find(row=>row[5]===name)!;return Object.fromEntries(parsed.header.map((key,i)=>[key,row[i]]));};
const render=(d:RangeData)=>renderToStaticMarkup(createElement(CustomRangeComparison,{range:d,currency:d.currency}));
const html=(d:RangeData)=>{const all=render(d);const start=all.indexOf(">"+name+"</th>");return all.slice(start,all.indexOf("</tr>",start));};
part("Compare monetization using each period's consolidated visitor estimate");
is("current uses consolidated visitors, not summed daily counts",metric(data).current,550);
is("previous uses its own visitor count",metric(data).previous,250);
is("absolute difference stays in minor units",metric(data).difference,300);
is("relative change compares the two ratios",metric(data).change,120);
is("ratio is monetary",metric(data).money,true);
is("sales count does not become the denominator",metric({...data,totals:{...data.totals,sales:100}}).current,550);
is("page views do not become the denominator",metric({...data,totals:{...data.totals,views:1000}}).current,550);
is("UI shows the monetary ratio and signed difference",html(data).includes("$5.50")&&html(data).includes("+$3"),true);
is("UI shows prior ratio and change",html(data).includes("$2.50")&&html(data).includes("+120%"),true);
is("CSV uses major units",[csv(data).Current,csv(data).Previous,csv(data).Difference],["5.5","2.5","3"]);
is("CSV preserves relative change",csv(data)["Change (%)"],"120");
part("Undefined denominators and incomplete ledgers remain unavailable");
const noVisitors={...data,totals:{...data.totals,visitors:0}};
is("revenue without measured visitors has no ratio",metric(noVisitors).current,null);
is("no current visitors has no difference or growth",[metric(noVisitors).difference,metric(noVisitors).change],[null,null]);
is("valid prior ratio survives current zero visitors",metric(noVisitors).previous,250);
is("unavailable denominator exports blank, not zero",[csv(noVisitors).Current,csv(noVisitors)["Current available"]],["","No"]);
is("no current visitors renders unavailable",html(noVisitors).includes("Unavailable"),true);
const noPriorVisitors={...data,before:{...data.before!,visitors:0}};
is("no prior visitors does not invent a zero ratio",metric(noPriorVisitors).previous,null);
is("no prior denominator has no growth",metric(noPriorVisitors).change,null);
is("missing history keeps current ratio",metric({...data,before:null}).current,550);
is("missing history has no prior ratio",metric({...data,before:null}).previous,null);
is("unknown previous revenue stays unavailable",metric({...data,before:{...data.before!,cents:null}}).previous,null);
for(const d of [{...data,partial:true},{...data,sales:"none" as const},{...data,sales:"error" as const}]){
 const row=metric(d);
 is("incomplete ledger withholds all ratio comparisons",[row.current,row.previous,row.difference,row.change],[null,null,null,null]);
 is("incomplete ratio remains blank in CSV",[csv(d).Current,csv(d).Previous,csv(d).Difference],["","",""]);
 is("traffic remains visible independently",customRangeComparison(d).rows.find(row=>row.name==="Visitors")?.current,20);
}
const zeroRevenue={...data,totals:{...data.totals,cents:0},before:{...data.before!,cents:0}};
is("zero revenue with positive traffic is a confirmed zero ratio",metric(zeroRevenue).current,0);
is("confirmed zero ratio retains absolute difference",metric(zeroRevenue).difference,0);
is("zero previous ratio has no relative percentage",metric(zeroRevenue).change,null);
part("Currency precision and honest metric definitions");
const fractional={...data,totals:{...data.totals,visitors:3,cents:100}};
is("ratio is not rounded before comparison",metric(fractional).current,100/3);
is("CSV retains fractional smallest-unit precision",csv(fractional).Current,String((100/3)/100));
is("JPY uses its own scale",csv({...fractional,currency:"jpy"}).Current,String(100/3));
is("KWD uses its own scale",csv({...fractional,currency:"kwd"}).Current,String((100/3)/1000));
is("definition identifies visitor estimates",csv(data).Definition.includes("recorded visitor estimate for each period"),true);
is("definition does not claim buyer attribution",csv(data).Definition.includes("not matched buyers"),true);
is("display explains period total versus daily chart",render(data).includes("not sums of daily counts"),true);
is("missing visitor denominator is explained",render(data).includes("no visitors means unavailable"),true);
is("input figures are unchanged",[data.totals.visitors,data.totals.cents,data.days[0].visitors],[20,11000,15]);
done();
