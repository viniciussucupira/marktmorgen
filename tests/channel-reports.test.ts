import { cashflowReport, buyerChannelReport } from "@/lib/channel-reports";
import { parseCsv } from "@/lib/csv";
import { ReportDownload } from "@/components/report-download";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const period = { from: "2026-10-07", to: "2026-10-13", currency: "usd" };
part("Channel export retains numeric losses and unknown results");
const row = { source: "instagram", receipts: 15000, refunds: 12000, adSpend: 5000, afterRefunds: 3000, afterAds: -2000, backPerOne: 0.6 };
const text = cashflowReport([row], period);
const parsed = parseCsv(text);
is("UTF-8 spreadsheet file", text.charCodeAt(0), 0xfeff);
is("explicit dates, currency and numeric result", parsed.rows[0].slice(0, 10), [period.from, period.to, "USD", "Instagram", "150", "120", "50", "30", "-20", "Complete"]);
is("negative amount is usable in arithmetic", Number(parsed.rows[0][8]), -20);
is("definitions travel with the report", parsed.rows[0][10].includes("not profit"), true);
const missing = parseCsv(cashflowReport([{ ...row, refunds: null, afterRefunds: null, afterAds: null, backPerOne: null }], period)).rows[0];
is("unknown refund and result are blank, never zero", [missing[5], missing[7], missing[8], missing[9]], ["", "", "", "Incomplete"]);
is("yen is not divided by a hundred", parseCsv(cashflowReport([row], { ...period, currency: "jpy" })).rows[0][4], "15000");
is("three decimal money is supported", parseCsv(cashflowReport([{ ...row, receipts: 12345 }], { ...period, currency: "kwd" })).rows[0][4], "12.345");
part("Untrusted channel text is never executed by spreadsheets");
const hostile = '=HYPERLINK("https://example.com")';
is("formula channel is escaped", parseCsv(cashflowReport([{ ...row, source: hostile }], period)).rows[0][3], "'" + hostile);
const named = 'Campanha São Paulo, "A"\nB';
is("commas, quotes, accents and linebreaks roundtrip", parseCsv(cashflowReport([{ ...row, source: named }], period)).rows[0][3], named);
part("Cohort export keeps maturity denominator, coverage and privacy");
const window = { rows: [{ source: "email", buyers: 3, repeatBuyers: 1, orders: 4, cents: 10000, eligible30: 2, repeated30: 1 }], unidentifiedOrders: 4 };
const buyer = parseCsv(buyerChannelReport(window, true, period)).rows[0];
is("amounts and mature cohort rate", buyer.slice(4, 14), ["3", "1", "4", "100", "33.33", "2", "1", "50", "Partial", "4"]);
is("rate is not calculated from all buyers", buyer[11], "50");
is("young cohort rate is unknown", parseCsv(buyerChannelReport({ ...window, rows: [{ ...window.rows[0], eligible30: 0, repeated30: 0 }] }, false, period)).rows[0][11], "");
is("unidentified-only report preserves excluded orders", parseCsv(buyerChannelReport({ rows: [], unidentifiedOrders: 7 }, false, period)).rows[0][13], "7");
is("no identities exported", /@|customer_details|receipt_email/.test(buyerChannelReport(window, true, period)), false);
is("empty cashflow is a valid header-only file", parseCsv(cashflowReport([], period)).rows.length, 0);
part("Download is a deliberate accessible button");
const markup = renderToStaticMarkup(createElement(ReportDownload, { csv: text, filename: "results.csv" }, "Download channel results"));
is("no prefetch or navigation starts a download", [markup.includes('type="button"'), markup.includes("Download channel results"), markup.includes("href="), markup.includes(text)], [true, true, false, false]);
done();
