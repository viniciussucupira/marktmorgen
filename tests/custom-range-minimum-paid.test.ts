import { customRangeView, customRangeSelectionTotals, effectiveCustomRangeMinimumPaidRecords } from "@/lib/custom-range-view";
import { customRangeChannelsReport, customRangeProductsReport, customRangeSelectionReport } from "@/lib/channel-reports";
import { CustomRangeResults } from "@/components/custom-range";
import { parseCsv } from "@/lib/csv";
import type { RangeData } from "@/lib/stats";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { done, is, part } from "./check";
const entries=[{id:"zero",traffic:100,sales:0,cents:0},{id:"small",traffic:5,sales:1,cents:5000},{id:"large",traffic:100,sales:5,cents:10000},{id:"edge",traffic:20,sales:3,cents:4000}];
const data:RangeData={from:"2026-10-01",to:"2026-10-02",currency:"usd",sales:"ok",partial:false,elsewhere:0,before:null,days:[],totals:{visitors:225,views:225,sales:9,checkouts:9,cents:19000},channels:entries.map(r=>({source:r.id,visits:r.traffic,sales:r.sales,cents:r.cents})),products:entries.map(r=>({id:r.id,views:r.traffic,checkouts:r.sales,sales:r.sales,cents:r.cents})),channelsTotal:20,channelsTruncated:true,productsTotal:30,productsTruncated:true};
const ids=(d:RangeData)=>[d.channels.map(r=>r.source),d.products.map(r=>r.id)];
const records=(text:string)=>{const p=parseCsv(text);return p.rows.map(r=>Object.fromEntries(p.header.map((key,i)=>[key,r[i]])));};
const render=(d:RangeData)=>renderToStaticMarkup(createElement(CustomRangeResults,{range:{...d,products:d.products.map(p=>({...p,title:p.id}))},marks:[],currency:d.currency}));
part("Only whole nonnegative paid-record thresholds are applied");
for(const raw of [0,"", " 0 ",undefined,-1,0.5,"1.5","bad",Infinity,NaN,Number.MAX_SAFE_INTEGER+1])is("invalid or empty minimum becomes zero",effectiveCustomRangeMinimumPaidRecords(data,raw),0);
is("valid string trimmed",effectiveCustomRangeMinimumPaidRecords(data," 3 "),3);
is("largest safe count supported",effectiveCustomRangeMinimumPaidRecords(data,Number.MAX_SAFE_INTEGER),Number.MAX_SAFE_INTEGER);
part("Paid minimum combines with the existing loaded-list view");
const selected=customRangeView(data,"","recorded","all",0,3);
is("inclusive boundary in both lists",ids(selected),[["large","edge"],["large","edge"]]);
is("zero minimum preserves original snapshot",customRangeView(data,"","recorded","all",0,0)===data,true);
is("blank minimum preserves original snapshot",customRangeView(data,"","recorded","all",0,"")===data,true);
is("search combined with minimum",ids(customRangeView(data,"edge","recorded","all",0,3)),[["edge"],["edge"]]);
is("traffic minimum combined",ids(customRangeView(data,"","recorded","all",50,3)),[["large"],["large"]]);
is("ratio ordering after threshold",ids(customRangeView(data,"","efficiency_desc","all",0,3)),[["edge","large"],["edge","large"]]);
is("sales filter with threshold",ids(customRangeView(data,"","recorded","paid",0,3)),ids(selected));
is("traffic without sales with positive minimum is empty",ids(customRangeView(data,"","recorded","unconverted",0,1)),[[],[]]);
is("no qualifying rows is empty",ids(customRangeView(data,"","recorded","all",0,6)),[[],[]]);
is("selection totals follow threshold",customRangeSelectionTotals(selected).channels,{rows:2,traffic:120,paidRecords:8,cents:14000});
is("source arrays unchanged",data.channels.map(r=>r.source),entries.map(r=>r.id));
is("period totals not filtered",selected.totals,data.totals);
is("source limits retained",[selected.channelsTotal,selected.channelsTruncated],[20,true]);
part("Exports record the applied minimum alongside the selected rows");
const selection={minimumPaidRecords:3,minimumTraffic:0,filter:"all" as const};
for(const report of [customRangeChannelsReport(selected,selection),customRangeProductsReport(selected,selection),customRangeSelectionReport(selected,selection)]){
 const rows=records(report);
 is("paid minimum metadata",rows.every(r=>r["Minimum paid records"]==="3"),true);
 is("minimum definition disclosed",rows.every(r=>r.Definition.includes("effective paid-count filter")),true);
}
is("channel CSV selection",records(customRangeChannelsReport(selected,selection)).length,2);
is("product CSV selection",records(customRangeProductsReport(selected,selection)).length,2);
is("summary selected paid records",records(customRangeSelectionReport(selected,selection)).map(r=>r["Paid records"]),["8","8"]);
part("Unknown payments cannot apply a hidden financial threshold");
for(const d of [{...data,partial:true},{...data,sales:"none" as const},{...data,sales:"error" as const}]){
 is("threshold disabled for unknown payments",effectiveCustomRangeMinimumPaidRecords(d,3),0);
 is("all observed rows remain",ids(customRangeView(d,"","recorded","all",0,3)),ids(d));
 const row=records(customRangeSelectionReport(d,{minimumPaidRecords:3}))[0];
 is("CSV reports inactive minimum",row["Minimum paid records"],"0");
 is("CSV does not invent paid count",row["Paid records"],"");
 const input=render(d).match(/<input[^>]*id="range-minimum-paid"[^>]*>/)?.[0]??"";
 is("paid minimum disabled in UI",input.includes('disabled=""'),true);
}
const malformed={...data,partial:true,channels:data.channels.map(r=>({...r,sales:NaN}))};
is("unknown paid counts do not hide traffic",customRangeView(malformed,"","traffic_desc","all",0,3).channels.length,4);
const html=render(data),input=html.match(/<input[^>]*id="range-minimum-paid"[^>]*>/)?.[0]??"";
is("accessible minimum label",html.includes('for="range-minimum-paid"'),true);
is("minimum enabled with complete payments",input.includes('disabled=""'),false);
is("count scope excludes unique buyers",html.includes("Payment records, not distinct buyers"),true);
is("count scope explains extras",html.includes("Channels exclude one-click extras; products include them"),true);
done();
