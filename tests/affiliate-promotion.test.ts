import { affiliateCampaignLink, affiliatePromotionFrom, affiliatePromotionRows, readAffiliatePromotion } from "@/lib/affiliate-promotion";
import { bookCsv, creditPayPalSale, noteCharge, noteSession, readBook } from "@/lib/affiliates";
import { NO_AFFILIATES } from "@/lib/affiliate-setting";
import type { Store } from "@/lib/store";
import { store as redis } from "./redis-stub";
import { done, is, part } from "./check";

async function main() {
 part("Campaign links keep affiliate credit and commercial parameters");
 const link = new URL(affiliateCampaignLink("https://shop.example/p/course?coupon=SAVE&via=old#details","sara","instagram","Launch","post","Story A"));
 is("affiliate replaced once",link.searchParams.getAll("via"),["sara"]);
 is("all campaign labels",[link.searchParams.get("utm_source"),link.searchParams.get("utm_campaign"),link.searchParams.get("utm_content")],["instagram","launch","story-a"]);
 is("coupon and anchor",[link.searchParams.get("coupon"),link.hash],["SAVE","#details"]);
 is("invalid code refused",affiliateCampaignLink("https://shop.example","<bad>","x","launch"),"");
 is("unsafe address refused",affiliateCampaignLink("javascript:alert(1)","sara","x","launch"),"");
 is("blank campaign refused",affiliateCampaignLink("https://shop.example","sara","x",""),"");
 part("Recorded labels preserve a coherent source family");
 is("older records remain unknown",affiliatePromotionFrom({}),null);
 is("do not mix current tags with earlier source",affiliatePromotionFrom({utm_campaign:"current",channel:"x",channel_content:"old"}),{source:"",campaign:"current",content:""});
 is("remembered family",affiliatePromotionFrom({channel:"instagram",channel_campaign:"launch",channel_content:"story-a"}),{source:"instagram",campaign:"launch",content:"story-a"});
 is("bounded labels",readAffiliatePromotion({source:"x".repeat(100),campaign:"a".repeat(100),content:"b".repeat(100)})?.content.length,40);
 is("malformed values",readAffiliatePromotion({source:123,campaign:[],content:{}}),null);
 is("array is not a label record",readAffiliatePromotion(["x"]),null);
 part("Checkout, added offer, PayPal, stored book and export share the same labels");
 redis.clear();
 const affiliate="aaaaaaaaaaaa";
 await redis.pipeline([["HSET","nl:aff:statsid1:people",affiliate,JSON.stringify({id:affiliate,email:"sara@example.com",code:"sara",status:"approved",appliedAt:1,decidedAt:1,note:""})]]);
 const store={sid:"storeid1",handle:"harbor",name:"Harbor",email:"owner@example.com",statsId:"statsid1",currency:"usd",previousHandles:[],releasedHandles:[],affiliates:{...NO_AFFILIATES,enabled:true,percent:20}} as unknown as Store;
 const meta={store:"harbor",product:"course",title:"Course",via:affiliate,via_rate:"20",utm_source:"instagram",utm_campaign:"launch",utm_content:"story-a"};
 const session={id:"cs_post1",mode:"payment",status:"complete",payment_status:"paid",created:1760000000,amount_total:10000,amount_subtotal:10000,currency:"usd",payment_intent:"pi_post1",metadata:meta,customer_details:{email:"buyer@example.com"}};
 await noteSession(store,session,new Map(),[]);
 await noteSession(store,session,new Map(),[]);
 await noteCharge(store,{id:"pi_extra1",status:"succeeded",amount:5000,currency:"usd",receipt_email:"buyer@example.com",created:1760000000,metadata:meta});
 await creditPayPalSale(store,{store:"storeid1",order:"PP1",capture:"CAP1",email:"buyer@example.com",product:"course",cents:5000,currency:"usd",at:1760000000,via:{aff:affiliate,rate:20},meta},"Course");
 let book=await readBook(store,affiliate);
 is("all three payment paths retain labels",book.lines.filter(l=>l.promotion?.content==="story-a").length,3);
 is("idempotent commission",book.lines.filter(l=>l.ref==="cs_post1").length,1);
 is("book parser preserves labels",book.lines.find(l=>l.ref==="cs_post1")?.promotion,{source:"instagram",campaign:"launch",content:"story-a"});
 const csv=bookCsv(book,[]);
 is("export headers",csv.split("\r\n")[0].endsWith("campaign_channel,campaign_name,post_variant"),true);
 is("export values",csv.includes("instagram,launch,story-a"),true);
 const grouped=affiliatePromotionRows(book.lines);
 is("groups actual purchases, not generated second-tier",grouped.map(g=>[g.paidRecords,g.commission]),[[3,4000]]);
 await redis.pipeline([["HSET","nl:aff:statsid1:sales","cs_legacy",JSON.stringify({ref:"cs_legacy",pi:"pi_legacy",aff:affiliate,at:1760000000,product:"course",title:"Course",base:1000,total:1000,currency:"usd",rate:20,self:false,how:"click"})]]);
 book=await readBook(store,affiliate);
 is("legacy line remains unlabelled",book.lines.find(l=>l.ref==="cs_legacy")?.promotion,undefined);
 const one=book.lines.find(l=>l.ref==="cs_post1")!;
 const variants=affiliatePromotionRows([one,{...one,ref:"second",promotion:{...one.promotion!,content:"story-b"}},{...one,ref:"euro",currency:"eur"},{...one,ref:"bonus",how:"bonus"},{...one,ref:"tier",how:"tier2"},{...one,ref:"own",self:true},one]);
 is("variants and currencies remain separate",variants.length,3);
 is("duplicates and derived lines do not inflate records",variants.reduce((n,r)=>n+r.paidRecords,0),3);
 done();
}
main().catch(error=>{console.error(error);process.exit(1);});
